def ninja_hero():
    """Ниндзя: тёмно-синяя куртка с запахом и капюшон с прорезью глаз, красный шарф вокруг шеи с
    двумя концами за спиной, меч наискось за спиной рукоятью над правым плечом, белые обмотки на
    голенях, тёмные таби с отдельным пальцем."""
    a = lm.Atlas(64, 64, 311)
    # Торс 32×20: середина куска это грудь, левая половина это правый бок героя. Четыре полосы
    # колец по пять строк: ворот, грудь, живот, бёдра.
    a.rect(0, 0, 32, 20, BLUE)
    a.rect(0, 0, 32, 2, BLUE_D)  # ворот под шарфом
    # Запах куртки: клин кольчужной рубахи у горла, левая пола поверх правой.
    for y in range(2, 9):
        half = (9 - y) // 2
        a.rect(16 - half, y, half * 2, 1, LACQ)
        for x in range(16 - half, 16 + half):
            if (x + y) % 2 == 0:
                a.px(x, y, STEEL)
    _line(a, 11, 2, 16, 10, BLUE_D)
    _line(a, 12, 2, 17, 10, BLUE_L)
    _line(a, 20, 2, 16, 9, BLUE_D)
    _line(a, 17, 10, 19, 14, BLUE_D)  # край полы уходит под пояс
    # Ремень меча: с правого плеча на левое бедро спереди, по спине так же через шов.
    _line(a, 9, 2, 23, 14, GOLD_D)
    _line(a, 10, 2, 24, 14, mul(GOLD_D, 0.7))
    a.px(15, 7, GOLD), a.px(16, 8, GOLD)  # пряжка
    _line(a, 7, 2, 0, 8, GOLD_D)
    _line(a, 31, 8, 25, 14, GOLD_D)
    # Складки и швы.
    for x, y, w in ((3, 6, 3), (26, 5, 4), (21, 11, 3), (4, 12, 4), (27, 11, 3)):
        a.rect(x, y, w, 1, BLUE_D)
    a.rect(21, 4, 3, 1, BLUE_L), a.rect(6, 9, 3, 1, BLUE_L), a.rect(12, 12, 2, 1, BLUE_L)
    # Пояс в два витка с узлом слева от пряжки, концы узла свисают на полу.
    a.rect(0, 15, 32, 2, LACQ)
    a.rect(0, 15, 32, 1, LACQ_L)
    a.rect(18, 14, 3, 4, LACQ), a.px(19, 15, LACQ_L)
    a.rect(18, 18, 1, 2, LACQ), a.rect(20, 18, 1, 2, LACQ_L)
    # Сумка с сюрикенами на правом боку.
    a.rect(5, 15, 4, 4, GOLD_D), a.rect(5, 15, 4, 1, STRAW), a.px(7, 17, GOLD)
    a.rect(0, 19, 32, 1, BLUE_D)  # кромка полы
    a.shade(0, 0, 32, 20, 1.1, 0.88, 0.74)
    a.noise(0, 0, 32, 20, 0.05)
    torso = a.region(0, 0, 32, 20)
    # Голова 32×20, пять полос по 4 строки: темя, лоб, глаза, нос и рот под тканью, шея.
    a.rect(0, 20, 32, 20, BLUE)
    a.rect(0, 20, 32, 1, BLUE_L)
    for x in (4, 10, 21, 27):
        a.rect(x, 21, 1, 5, BLUE_D)  # складки капюшона от темени
    a.rect(15, 20, 2, 3, BLUE_D)  # шов по темени
    a.rect(12, 25, 8, 1, BLUE_L)  # блик на лбу
    a.rect(8, 27, 16, 1, BLUE_D)  # кромка капюшона над глазами
    a.rect(9, 28, 14, 4, SKIN)
    a.rect(9, 28, 14, 1, SKIN_D)  # тень капюшона на лбу
    for x, y in ((9, 28), (22, 28), (9, 31), (22, 31)):
        a.px(x, y, BLUE)
    _eyes(a, 30, BLACK)
    a.rect(15, 30, 2, 2, mul(SKIN, 0.92))  # переносица
    a.rect(8, 32, 16, 1, BLUE_D)  # кромка маски под глазами
    a.rect(15, 33, 2, 2, BLUE_L)  # нос под тканью
    _line(a, 14, 34, 10, 35, BLUE_D), _line(a, 17, 34, 21, 35, BLUE_D)  # складки от носа
    a.rect(13, 35, 6, 1, BLUE_D)
    for x in (0, 1, 30, 31):
        a.rect(x, 24, 1, 10, BLUE_D)  # складка на затылке
    a.rect(2, 29, 3, 1, BLUE_D), a.rect(27, 29, 3, 1, BLUE_D)
    a.rect(0, 36, 32, 4, BLUE_D)
    a.shade(0, 20, 32, 20, 1.12, 0.88, 0.8)
    a.noise(0, 20, 32, 20, 0.04)
    head = a.region(0, 20, 32, 20)
    # Рука 16×16: рукав со складками, стянут у локтя, наруч в белой шнуровке, кисть.
    a.rect(32, 0, 16, 9, BLUE)
    a.rect(32, 0, 16, 1, BLUE_L)
    for x, y, w in ((33, 2, 4), (41, 4, 5), (35, 6, 4)):
        a.rect(x, y, w, 1, BLUE_D)
    a.rect(32, 7, 16, 2, BLUE_D)
    a.px(39, 7, WHITE), a.px(40, 8, WHITE)  # завязка у локтя
    _wraps(a, 32, 9, 16, 4, LACQ, GREY)
    a.rect(32, 9, 16, 1, LACQ_L)
    a.rect(32, 13, 16, 3, SKIN)
    a.rect(36, 13, 8, 1, LACQ)  # наруч заходит на тыл кисти
    a.rect(32, 15, 16, 1, SKIN_D)
    for x in (35, 39, 43):
        a.px(x, 14, SKIN_D)
    a.shade(32, 0, 16, 16, 1.06, 0.9, 0.76)
    a.noise(32, 0, 16, 16, 0.05)
    arm = a.region(32, 0, 16, 16)
    # Нога 16×24: широкая штанина со складками, стянута под коленом, белая обмотка с косыми
    # витками, таби с разрезом между пальцами и ремешком.
    a.rect(48, 0, 16, 13, BLUE)
    a.rect(55, 0, 1, 10, mul(BLUE, 0.8))
    for x0, y0, x1, y1 in ((49, 3, 52, 4), (59, 7, 62, 8)):
        _line(a, x0, y0, x1, y1, BLUE_D)
    a.rect(57, 1, 3, 1, BLUE_L), a.rect(51, 5, 3, 1, BLUE_L)
    a.rect(48, 10, 16, 3, BLUE_D)
    a.rect(48, 10, 16, 1, mul(BLUE, 0.8))
    a.px(55, 11, WHITE), a.px(56, 12, WHITE)  # завязка штанины
    _wraps(a, 48, 13, 16, 5, WHITE, GREY)
    a.rect(48, 13, 16, 1, GREY)
    a.rect(48, 18, 16, 6, LACQ)
    a.rect(48, 18, 16, 1, LACQ_L)
    a.rect(48, 20, 16, 1, RED_D)  # ремешок
    a.rect(55, 21, 1, 3, BLACK)  # разрез между пальцами
    a.rect(48, 23, 16, 1, STRAW_D)  # соломенная подошва
    a.shade(48, 0, 16, 24, 1.06, 0.88, 0.76)
    a.noise(48, 0, 16, 24, 0.05)
    leg = a.region(48, 0, 16, 24)
    # Шарф 16×6 кольцом вокруг шеи: складки наискось.
    a.rect(32, 16, 16, 6, RED)
    a.rect(32, 16, 16, 1, RED_L)
    for x in range(32, 48, 4):
        _line(a, x, 17, x + 2, 20, RED_D)
    a.rect(32, 21, 16, 1, RED_D)
    a.noise(32, 16, 16, 6, 0.06)
    scarf = a.region(32, 16, 16, 6)
    a.rect(32, 22, 4, 4, LACQ_D)
    a.rect(36, 22, 4, 4, BLUE), a.px(37, 23, BLUE_L)
    a.rect(40, 22, 4, 4, GOLD), a.px(41, 23, GOLD_L), a.rect(40, 25, 4, 1, GOLD_D)
    sole, crown, gold = a.region(32, 22, 4, 4), a.region(36, 22, 4, 4), a.region(40, 22, 4, 4)
    # Концы шарфа 8×20 каждый: складка вдоль, светлая кромка, конец ласточкиным хвостом.
    for x0 in (0, 8):
        a.rect(x0, 44, 8, 20, RED)
        a.rect(x0, 44, 1, 20, RED_L)
        a.rect(x0 + 4 + x0 // 8, 44, 1, 18, RED_D)
        a.rect(x0 + 7, 44, 1, 20, RED_D)
        for y in (48, 53, 58):
            a.rect(x0 + 1, y + x0 // 4, 3, 1, RED_D)
        a.clear(x0 + 2, 63, 4, 1), a.clear(x0 + 3, 61, 2, 2)
    a.noise(0, 44, 16, 20, 0.06)
    tail_a, tail_b = a.region(0, 44, 8, 20), a.region(8, 44, 8, 20)
    # Ножны 8×20 (четыре грани по два пикселя): чёрный лак с бликом, золотое устье и наконечник,
    # красный шнур на скобе.
    a.rect(16, 44, 8, 20, LACQ)
    for x in (16, 20):
        a.rect(x, 44, 1, 20, LACQ_L)
    a.rect(16, 44, 8, 2, GOLD), a.rect(16, 45, 8, 1, GOLD_D)
    a.rect(16, 49, 8, 1, GOLD_D)
    a.rect(16, 50, 8, 2, RED), a.px(17, 52, RED), a.px(17, 53, RED_D), a.px(21, 52, RED)
    a.rect(16, 61, 8, 3, GOLD), a.rect(16, 63, 8, 1, GOLD_D)
    a.noise(16, 44, 8, 20, 0.05)
    sheath = a.region(16, 44, 8, 20)
    # Рукоять 8×10: оплётка ромбами, навершие и муфта золотом.
    a.rect(24, 44, 8, 10, LACQ_D)
    for j in range(1, 9):
        for i in range(8):
            if (i + j) % 2 == 0:
                a.px(24 + i, 44 + j, GREY if j % 2 else WHITE)
    a.rect(24, 44, 8, 1, GOLD), a.rect(24, 53, 8, 1, GOLD_D)
    hilt = a.region(24, 44, 8, 10)

    parts = lm.biped(leg, torso, head, arm, sole, crown)
    # Узкий корпус, плечи шире ворота, чтобы рукава сидели на торсе без щели.
    parts["body"][1] = lm.loft([(0.82, 0.165, 0.112), (1.02, 0.15, 0.098), (1.27, 0.2, 0.122), (1.42, 0.207, 0.1),
                                (1.47, 0.06, 0.06)], torso, 6)
    # Голова в капюшоне: гладкий купол, чуть шире лица на уровне глаз, темя сходится в точку.
    parts["head"][1] = lm.loft([(1.44, 0.055, 0.06), (1.5, 0.088, 0.098, 0.0, -0.004), (1.57, 0.104, 0.114),
                                (1.64, 0.108, 0.118), (1.72, 0.098, 0.108), (1.775, 0.0, 0.0)], head, 6)
    body = parts["body"][1]
    # Шарф: валик вокруг шеи, низом утоплен в плечи, верхом закрывает подбородок.
    body.extend(lm.loft([(1.385, 0.11, 0.095), (1.46, 0.132, 0.126), (1.535, 0.09, 0.098)], scarf, 6))
    # Два конца шарфа от затылка назад и вниз: длинный к левому боку, короткий к правому, оба с
    # перегибом и лёгкой скруткой, чтобы читались и сзади, и сбоку.
    body.extend(_ribbon([((-0.035, 1.47, 0.115), (0.04, 0.0, 0.0)), ((-0.085, 1.39, 0.27), (0.042, 0.014, 0.0)),
                         ((-0.13, 1.25, 0.36), (0.038, 0.026, 0.0)), ((-0.19, 1.07, 0.4), (0.032, 0.034, 0.004))],
                        tail_a))
    body.extend(_ribbon([((0.035, 1.47, 0.115), (0.036, 0.0, 0.0)), ((0.09, 1.4, 0.27), (0.038, -0.016, 0.0)),
                         ((0.14, 1.22, 0.36), (0.03, -0.028, 0.0))], tail_b))
    # Меч за спиной (спина это +Z): ножны от правого плеча к левому бедру, цуба, рукоять над плечом.
    sword = lm.loft([(-0.42, 0.022, 0.016), (0.16, 0.03, 0.021)], sheath, 4, math.pi / 4.0, caps=(gold, None), flat=True)
    sword += lm.quad((-0.042, 0.167, -0.032), (0.042, 0.167, -0.032), (0.042, 0.167, 0.032), (-0.042, 0.167, 0.032), gold)
    sword += lm.loft([(0.167, 0.022, 0.017), (0.4, 0.022, 0.017)], hilt, 4, math.pi / 4.0, caps=(None, gold), flat=True)
    body.extend(lm.at(lm.rot(sword, rz=-38.0), 0.0, 1.22, 0.135))
    return lm.assemble("hero", a, parts)


# --- Ниндзя чужого клана -----------------------------------------------------------------------

def ninja_enemy():
    """Ниндзя чужого клана: красная куртка и штаны, чёрная маска с завязками на затылке и
    стальной пластиной на лбу, чёрные наручи и голени, серп кама в правой руке."""
    a = lm.Atlas(64, 64, 323)
    # Тело 32×20: четыре полосы по пять строк. Чёрный ворот маски, запах куртки, герб клана на
    # спине (шов куска), чёрный пояс с золотой пряжкой, пола.
    a.rect(0, 0, 32, 20, RED)
    a.rect(0, 0, 32, 3, LACQ)
    a.rect(0, 2, 32, 1, LACQ_D)
    for y in range(3, 9):
        half = (9 - y) // 2 + 1
        a.rect(16 - half, y, half * 2, 1, LACQ)
    _line(a, 11, 3, 16, 10, CLAY)
    _line(a, 12, 3, 17, 10, RED_L)
    _line(a, 20, 3, 16, 9, CLAY)
    _line(a, 17, 10, 19, 14, CLAY)
    for x, y, w in ((3, 6, 3), (25, 6, 4), (21, 11, 3), (5, 12, 4), (26, 12, 3)):
        a.rect(x, y, w, 1, CLAY)
    a.rect(6, 4, 3, 1, RED_L), a.rect(22, 8, 3, 1, RED_L)
    # Герб на спине: белое кольцо с красной точкой на чёрном, половинами по обе стороны шва.
    a.rect(0, 6, 3, 5, LACQ), a.rect(29, 6, 3, 5, LACQ)
    a.rect(0, 6, 2, 1, WHITE), a.rect(30, 6, 2, 1, WHITE), a.rect(0, 10, 2, 1, WHITE), a.rect(30, 10, 2, 1, WHITE)
    a.rect(2, 7, 1, 3, WHITE), a.rect(29, 7, 1, 3, WHITE)
    a.px(2, 6, RED), a.px(2, 10, RED), a.px(29, 6, RED), a.px(29, 10, RED)
    a.px(0, 8, RED), a.px(31, 8, RED)
    a.rect(0, 15, 32, 2, LACQ)
    a.rect(0, 15, 32, 1, LACQ_L)
    a.rect(15, 15, 2, 2, GOLD), a.px(15, 16, GOLD_D)
    a.rect(11, 17, 1, 3, CLAY), a.rect(20, 17, 1, 3, CLAY)  # разрезы полы
    a.rect(0, 19, 32, 1, CLAY)
    a.shade(0, 0, 32, 20, 1.08, 0.86, 0.74)
    a.noise(0, 0, 32, 20, 0.05)
    body = a.region(0, 0, 32, 20)
    # Голова 32×20, пять полос по 4 строки: темя, лоб с повязкой и стальной пластиной, прорезь
    # с глазами, низ маски, шея.
    a.rect(0, 20, 32, 20, LACQ)
    a.rect(0, 20, 32, 1, LACQ_L)
    for x in (5, 11, 20, 26):
        a.rect(x, 21, 1, 3, LACQ_D)
    a.rect(13, 22, 6, 1, LACQ_L)
    a.rect(0, 24, 32, 3, LACQ_L)  # повязка вокруг головы
    a.rect(0, 26, 32, 1, LACQ_D)
