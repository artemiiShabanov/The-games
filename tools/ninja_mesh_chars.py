import lowpoly_meshes as lm  # noqa: E402
import ninja16 as n16  # noqa: E402

rgb, mul = lm.rgb, lm.mul


def _pal(i):
    return tuple(n16.PALETTE[i])


# Цвета из палитры основы 16/32, светлые и тёмные тона к ним.
BLACK = _pal(n16.K)
BLUE, BLUE_D, BLUE_L = _pal(n16.SEA), _pal(n16.NAVY), rgb("5A6CC6")
RED, RED_D, RED_L = _pal(n16.RED), rgb("96222E"), rgb("F0705A")
CLAY = _pal(n16.TAN)
WHITE, GREY = _pal(n16.WHITE), _pal(n16.GREY)
SKIN, SKIN_D = _pal(n16.SKIN), rgb("C88E6C")
GOLD, GOLD_D, GOLD_L = _pal(n16.GOLD), _pal(n16.BRASS), rgb("FCE89A")
STEEL, STEEL_D = _pal(n16.METAL), rgb("4E5062")
LACQ, LACQ_D, LACQ_L = _pal(n16.DARK), rgb("211E2B"), rgb("575270")
STRAW, STRAW_D = rgb("D2A85A"), _pal(n16.BRASS)
CAPE, CAPE_D, CAPE_L = rgb("7E1C2A"), rgb("4C1020"), rgb("A83240")


def _line(a, x0, y0, x1, y1, c):
    """Линия в один пиксель между двумя точками атласа."""
    n = max(abs(x1 - x0), abs(y1 - y0), 1)
    for i in range(n + 1):
        a.px(int(round(x0 + (x1 - x0) * i / n)), int(round(y0 + (y1 - y0) * i / n)), c)


def _wraps(a, x, y, w, h, base, cord, step=4):
    """Обмотка: полоса ткани с косыми витками шнура."""
    a.rect(x, y, w, h, base)
    for j in range(h):
        for i in range(w):
            if (i + j * 2) % step == 0:
                a.px(x + i, y + j, cord)


def _lames(a, x, y, w, rows, base, lace, edge=None):
    """Пластины доспеха рядами по три строки: блик лака, тело, шнуровка стежками через один."""
    for r in range(rows):
        a.rect(x, y + r * 3, w, 1, mul(base, 1.45))
        a.rect(x, y + r * 3 + 1, w, 1, base)
        a.rect(x, y + r * 3 + 2, w, 1, mul(base, 0.7))
        for i in range(x + (r % 2), x + w, 2):
            a.px(i, y + r * 3 + 2, lace)
    if edge:
        a.rect(x, y + rows * 3 - 1, w, 1, edge)


def _ribbon(points, region):
    """Лента из плоских звеньев: точки это (середина, полуширина-вектор), кусок атласа делится по
    длине поровну. Двусторонняя."""
    u0, v0, u1, v1 = region
    n = len(points) - 1
    tris = []
    for i in range(n):
        (c0, h0), (c1, h1) = points[i], points[i + 1]
        tl = tuple(c0[k] - h0[k] for k in range(3))
        tr = tuple(c0[k] + h0[k] for k in range(3))
        bl = tuple(c1[k] - h1[k] for k in range(3))
        br = tuple(c1[k] + h1[k] for k in range(3))
        tris += lm.quad(tl, tr, br, bl, (u0, v0 + (v1 - v0) * i / n, u1, v0 + (v1 - v0) * (i + 1) / n))
    return tris


def _eyes(a, y, brow, left=(11, 13), right=(18, 20)):
    """Глаза в прорези маски, строка `y`: сведённые брови строкой выше, белок и зрачок."""
    for x in range(left[0], left[1] + 1):
        a.px(x, y - 1 + (1 if x == left[1] else 0), brow)
    for x in range(right[0], right[1] + 1):
        a.px(x, y - 1 + (1 if x == right[0] else 0), brow)
    a.px(left[0], y, WHITE), a.px(left[0] + 1, y, BLACK)
    a.px(right[1], y, WHITE), a.px(right[1] - 1, y, BLACK)


