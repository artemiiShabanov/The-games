"""Персонажи «Ниндзя» для low poly и «продвинутых» (#137): ниндзя, ниндзя чужого клана, сёгун.
Зеркала `pirate_hero`, `pirate_enemy`, `pirate_captain` из `lowpoly_meshes.py` и космических из
`space_mesh_chars.py`: те же имена частей, родители и точки вращения (демки анимируют части),
взгляд в −Z, ноль в подошвах, рост не выше 1,93 м; у чужого клана оружие в правой руке на месте
сабли скелета (серп кама: древко вперёд, клюв вниз, на замахе он смотрит на героя). Цвета и
облик из основы 16/32 (`ninja16.PALETTE`): герой в тёмно-синем с капюшоном, красным шарфом в
два конца и мечом за спиной, белые обмотки на голенях; чужой клан в красном с чёрной маской,
стальной пластиной на лбу и чёрными голенями; сёгун в чёрном лаке с красной шнуровкой и
золотом, рогатый шлем с назатыльником, маска демона, наплечники, юбка из пластин и накидка.
Плотный набор «продвинутых» получается из этих же функций (плотность и размер атласа задаёт
`lowpoly_meshes`), поэтому геометрия собирается его помощниками.

    python3 tools/ninja_mesh_chars.py --preview out.png
"""
