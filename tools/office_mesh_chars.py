def _tie(a, x0, y0, h, c, c_d, c_l):
    """Галстук в куске 8×h: узел, лента, которая книзу шире, острый кончик; косые полоски.
    Остальное прозрачно."""
    for j in range(h):
        if j < 3:
            w = 4 if j < 2 else 2
        elif j >= h - 3:
            w = (h - j) * 2
        else:
            w = 2 + int(round(4.0 * (j - 3) / max(h - 7, 1)))
            w += w % 2
        x = x0 + 4 - w // 2
        for i in range(x, x + w):
            a.px(i, y0 + j, c_d if (i + j) % 4 == 0 else c)
        if w >= 4 and j >= 3:
            a.px(x, y0 + j, c_l)
            a.px(x + w - 1, y0 + j, c_d)
    a.rect(x0 + 2, y0 + 2, 4, 1, c_d)  # тень под узлом


def _tie_mesh(a, x0, y0, h, path, width=0.09):
    """Галстук лентой из плоскостей по точкам `(y, z, x)` сверху вниз: лежит на груди с зазором,
    кусок атласа делится между звеньями поровну."""
    tris = []
    n = len(path) - 1
    hw = width / 2.0
    for i in range(n):
        (ya, za, xa), (yb, zb, xb) = path[i], path[i + 1]
        tris += lm.quad((xa + hw, ya, za), (xa - hw, ya, za), (xb - hw, yb, zb), (xb + hw, yb, zb),
                        a.region(x0, y0 + h * i // n, 8, h * (i + 1) // n - h * i // n))
    return tris


def _hands(parts, arm, palm, k=1.0):
    """Предплечья `biped` с теми же кольцами, но с ладонью в цвет кожи на торце (у `biped` там
    кусок подошвы)."""
    u0, v0, u1, v1 = arm

    def cut(top, bottom):
        return (u0, v0 + (v1 - v0) * top, u1, v0 + (v1 - v0) * bottom)

    for side, x in (("l", -0.25 * k), ("r", 0.25 * k)):
        parts["fore_" + side][1] = lm.loft(
            [(0.78, 0.035 * k, 0.045, x * 1.08, 0.0), (1.13, 0.045 * k, 0.05 * k, x * 1.06, 0.0)],
            cut(0.47, 1.0), 4, math.pi / 4.0, caps=(palm, cut(0.45, 0.53)))


def _shoe(a, x, y, w=16, h=7):
    """Низ куска ноги: чёрный ботинок с бликом на носке (перёд в середине), шнурки, подошва."""
    a.rect(x, y, w, h, DARK_D)
    a.rect(x, y, w, 1, DARK_L)
    a.rect(x + w // 2 - 2, y + 1, 4, 2, DARK)
    a.px(x + w // 2 - 1, y + 1, GREY), a.px(x + w // 2, y + 2, GREY)  # шнурки
    a.rect(x + w // 2 - 2, y + h - 3, 4, 1, METAL)  # блик на носке
    a.rect(x, y + h - 1, w, 1, K)


