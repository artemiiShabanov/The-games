def _cut_poly(p, points):
    """Прозрачный многоугольник (зубцы рваного края, просветы между перьями)."""
    rm.ImageDraw.Draw(p.a).polygon([(x * p.k, y * p.k) for x, y in points], fill=0)


def _jag(p, x, y, w, teeth, lo, hi):
    """Рваный низ куска: `teeth` прозрачных клиньев от линии `y` вверх на случайную глубину."""
    step = w / teeth
    for i in range(teeth):
        x0 = x + i * step
        depth = p.rng.uniform(lo, hi)
        mid = x0 + step * p.rng.uniform(0.35, 0.65)
        _cut_poly(p, [(x0 + step * 0.04, y + 0.2), (mid, y - depth), (x0 + step * 0.96, y + 0.2)])


def _strokes(p, x, y, w, h, count, colors, length=1.0, width=0.1, lean=0.25):
    """Ворс, пряди: короткие почти вертикальные штрихи."""
    for i in range(count):
        sx, sy = x + p.rng.uniform(0.0, 1.0) * w, y + p.rng.uniform(0.0, 1.0) * h
        ln = length * p.rng.uniform(0.5, 1.0)
        ex = min(max(sx + p.rng.uniform(-lean, lean) * ln, x), x + w)
        p.line([(sx, sy), (ex, min(sy + ln, y + h))], colors[i % len(colors)], width)


def _hide(p, x, y, w, h, spots, height=142):
    """Шкура: оранжевая, с тёмными пятнами неровной формы, ворсом и выгоревшими местами."""
    p.rect(x, y, w, h, HIDE, height)
    p.grain(x, y, w, h, 0.07, 0.9, 10.0)
    p.uneven(x, y, w, h, 0.09, 2.6)
    _strokes(p, x, y, w, h, int(w * h / 3), (HIDE_D, HIDE_L, HIDE_D), 0.9, 0.09)
    for _ in range(spots):
        cx, cy = x + p.rng.uniform(0.08, 0.92) * w, y + p.rng.uniform(0.1, 0.9) * h
        size = p.rng.uniform(0.5, 0.95)
        for _ in range(3):
            ox, oy = p.rng.uniform(-0.5, 0.5) * size, p.rng.uniform(-0.5, 0.5) * size
            ex, ey = min(max(cx + ox, x + size), x + w - size), min(max(cy + oy, y + size * 0.8), y + h - size * 0.8)
            p.ellipse(ex, ey, size * p.rng.uniform(0.55, 1.0), size * p.rng.uniform(0.45, 0.8), HAIR)
        p.ellipse(min(max(cx, x + 0.3), x + w - 0.3), min(max(cy, y + 0.3), y + h - 0.3), size * 0.3, size * 0.25, HAIR_D)


def _fur(p, x, y, w, h, base=FUR, dark=FUR_D, height=166):
    """Меховая кромка или обмотка: светлый ворс с тёмными прядями."""
    p.rect(x, y, w, h, base, height)
    _strokes(p, x, y, w, h, int(w * h * 2.2), (dark, mul(base, 1.04), mix(base, dark, 0.4)), min(h, 1.3), 0.12, 0.4)
    p.grain(x, y, w, h, 0.06, 0.8, 14.0)


def _skin(p, x, y, w, h, base=SKIN):
    """Загорелая кожа: мелкое зерно, разводы."""
    p.rect(x, y, w, h, base, 128)
    p.grain(x, y, w, h, 0.035, 1.0, 5.0)
    p.uneven(x, y, w, h, 0.06, 3.0)


def _bone_tex(p, x, y, w, h, cracks=5, height=160):
    """Кость: тёплая белая, с разводами, трещинами и щербинами."""
    p.rect(x, y, w, h, BONE, height)
    p.grain(x, y, w, h, 0.04, 1.0, 8.0)
    p.uneven(x, y, w, h, 0.07, 2.4)
    for _ in range(cracks):
        cx, cy = x + p.rng.uniform(0.1, 0.9) * w, y + p.rng.uniform(0.1, 0.9) * h
        pts = [(cx, cy)]
        for _ in range(3):
            cx = min(max(cx + p.rng.uniform(-0.8, 0.8), x), x + w)
            cy = min(max(cy + p.rng.uniform(0.3, 0.9), y), y + h)
            pts.append((cx, cy))
        p.line(pts, BONE_DD, 0.1, 120)
    p.speckle(x, y, w, h, int(w * h / 6), BONE_D, 0.1)


def _scales(p, x, y, w, h, base=SCALE, size=0.8):
    """Чешуя: ряды округлых чешуек со сдвигом через ряд, у каждой светлая середина и тёмный
    край; под ней разводы."""
    p.rect(x, y, w, h, base, 132)
    p.uneven(x, y, w, h, 0.08, 2.6)
    gx, gy = p._grid(x, y, w, h)
    row = np.floor(gy / size)
    fx = np.mod(gx / size + 0.5 * np.mod(row, 2.0), 1.0) - 0.5
    fy = np.mod(gy / size, 1.0) - 0.42
    d = np.sqrt(fx * fx + fy * fy)
    edge = np.clip((d - 0.3) / 0.22, 0.0, 1.0)
    p._apply(x, y, w, h, (1.09 - 0.3 * edge).astype(np.float32), ((0.34 - d) * 60.0).astype(np.float32))


def _stripes(p, x, y, w, h, ys, color=SCALE_D, taper=True):
    """Тёмные поперечные полосы через хребет: клином к бокам."""
    for sy in ys:
        t = 0.5 if taper else 1.0
        p.poly([(x, y + sy - 0.55), (x + w, y + sy - 0.55 * t + 0.25), (x + w, y + sy + 0.25 + 0.2 * t), (x, y + sy + 0.6)], color, 140)


def _claws(p, xs, y, length, half=0.42, color=BONE):
    """Когти: белые клинья остриём вниз."""
    for cx in xs:
        p.poly([(cx - half, y), (cx + half, y), (cx + half * 0.2, y + length)], color, 176)
        p.line([(cx - half * 0.5, y + 0.1), (cx, y + length * 0.9)], BONE_D, 0.1)


def _fingers(p, y0, color, xs=(5.2, 7.0, 8.8, 10.6)):
    for fx in xs:
        p.line([(fx, y0), (fx, 48)], color, 0.22, 104)


def _bare_foot(p, skin, dark, light):
    """Босая ступня (кусок сапога): подъём, пять пальцев спереди с ногтями, пятка."""
    _skin(p, 40, 24, 12, 6, skin)
    p.fold([(40, 26.2), (52, 26.2)], 0.4, 0.86, 20)
    p.rect(40, 29.4, 12, 0.6, dark, 120)
    for i, tx in enumerate((43.4, 44.6, 45.8, 47.0, 48.2)):
        p.ellipse(tx, 28.6, 0.52, 0.72, mix(skin, light, 0.5), 150)
        p.ellipse(tx, 28.3, 0.3, 0.26, light, 160)
        p.line([(tx + 0.6, 27.8), (tx + 0.6, 29.6)], dark, 0.12, 110)
    p.line([(42.8, 27.8), (42.8, 29.6)], dark, 0.12, 110)
    p.shade_round(40, 24, 12, 6, 0.74)
    p.rect(54, 24, 6, 6, mul(dark, 0.82), 128)
    p.rect(54, 32, 6, 6, skin, 128)


def _eye(p, ex, ey, rx, ry, look=0.0):
    """Человеческий глаз: белок, зрачок, блик, веко сверху."""
    p.ellipse(ex, ey, rx * 1.22, ry * 1.3, SKIN_D, 118)
    p.ellipse(ex, ey, rx, ry, BONE, 132)
    p.ellipse(ex + look, ey + ry * 0.1, rx * 0.5, ry * 0.86, BLACK)
    p.ellipse(ex + look - rx * 0.2, ey - ry * 0.3, rx * 0.16, ry * 0.2, rgb("FFFFFF"))


def _hair(p, x, y, w, h, strands):
    """Лохматые волосы: тёмная масса, пряди светлее и темнее."""
    p.rect(x, y, w, h, HAIR, 152)
    p.uneven(x, y, w, h, 0.1, 2.0)
    _strokes(p, x, y, w, h, strands, (HAIR_L, HAIR_D, HAIR_D, mix(HAIR, HAIR_L, 0.5)), 4.2, 0.2, 0.22)
    p.grain(x, y, w, h, 0.07, 0.7, 12.0)


