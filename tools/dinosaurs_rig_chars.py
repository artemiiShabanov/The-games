def regions(p):
    reg = rm.regions(p)
    reg["own_head"] = reg["head"]
    reg["head"] = p.region(*INNER)
    reg["hem"] = p.region(*HEM)
    reg["teeth"] = p.region(*TEETH)
    reg["shaft"] = p.region(*SHAFT)
    reg["club"] = p.region(*CLUB)
    reg["tail"] = p.region(*TAIL)
    return reg


def head_tube(r, reg, rings, top):
    """Своя голова поверх спрятанной: кольца `(y, rx, rz)` или `(y, rx, rz, cz)` снизу вверх,
    перёд по центру куска головы, макушка на высоте `top`."""
    full = [(q[0], q[1], q[2], 0.0, q[3] if len(q) > 3 else -0.005) for q in rings]
    r.tube(full, 16, reg["own_head"], lambda y: [("head", 1.0)], cap_top=reg["crown"], v_range=(1.47, top))


def path_tube(r, rings, n, region, weight_fn, hint=(0.0, 1.0, 0.0), cap_start=None, cap_end=None):
    """Труба вдоль произвольного пути (морда, хвост, кость наискось): кольца `(центр, радиус вбок,
    радиус вверх)` стоят поперёк пути. Вокруг трубы развёртка идёт по ширине куска, шов снизу,
    верх (сторона `hint`) в середине куска; вдоль пути от низа куска к верху."""
    u0, v0, u1, v1 = region
    cs = [np.array(q[0], dtype=float) for q in rings]
    dist = [0.0]
    for a, b in zip(cs, cs[1:]):
        dist.append(dist[-1] + float(np.linalg.norm(b - a)))
    hint = np.array(hint, dtype=float)
    rows, dirs = [], []
    for i, (_, rs, ru) in enumerate(rings):
        d = cs[min(i + 1, len(cs) - 1)] - cs[max(i - 1, 0)]
        d = d / np.linalg.norm(d)
        up = hint - d * float(hint @ d)
        up = up / np.linalg.norm(up)
        side = np.cross(d, up)
        t = dist[i] / dist[-1]
        row = []
        for k in range(n + 1):
            a = 2.0 * math.pi * k / n
            pos = cs[i] + side * rs * math.sin(a) - up * ru * math.cos(a)
            pos = tuple(float(c) for c in pos)
            row.append(r.vert(pos, (u0 + (u1 - u0) * k / n, v1 - (v1 - v0) * t), weight_fn(t, pos)))
        rows.append(row)
        dirs.append(d)
    for i in range(len(rows) - 1):
        axis = (cs[i] + cs[i + 1]) / 2.0
        for k in range(n):
            a, b, c, d = rows[i][k], rows[i][k + 1], rows[i + 1][k + 1], rows[i + 1][k]
            out = np.mean([r.verts[j] for j in (a, b, c, d)], axis=0) - axis
            r.tri(a, b, c, out)
            r.tri(a, c, d, out)
    for cap, i, sign in ((cap_start, 0, -1.0), (cap_end, len(rows) - 1, 1.0)):
        if cap is None:
            continue
        uv = ((cap[0] + cap[2]) / 2.0, (cap[1] + cap[3]) / 2.0)
        t = dist[i] / dist[-1]
        center = r.vert(tuple(float(c) for c in cs[i]), uv, weight_fn(t, tuple(cs[i])))
        rim = [r.vert(r.verts[rows[i][k]], uv, weight_fn(t, r.verts[rows[i][k]])) for k in range(n)]
        for k in range(n):
            r.tri(center, rim[k], rim[(k + 1) % n], dirs[i] * sign)
    return rows


def _hem(r, region, rings, sway=0.45):
    """Подол вокруг бёдер: труба от пояса вниз. Низ ходит за ногами (правая половина за правой
    ногой, левая за левой, середина за обеими), поэтому шаг не протыкает шкуру."""
    first = len(r.verts)
    r.tube(rings, 16, region, lambda y: [("hips", 1.0)])
    top, bottom = rings[-1][0], rings[0][0]
    for j in range(first, len(r.verts)):
        x, y, _ = r.verts[j]
        t = max(0.0, min(1.0, (top - y) / (top - bottom)))
        if x > 0.04:
            legs = [("leg_r", 0.6 * t)]
        elif x < -0.04:
            legs = [("leg_l", 0.6 * t)]
        else:
            legs = [("leg_l", 0.3 * t), ("leg_r", 0.3 * t)]
        ws = [("hips", 1.0 - 0.6 * t)] + legs
        r.weights[j] = [(b, w) for b, w in sorted(ws, key=lambda item: -item[1]) if w > 0.0]
        r.cloth[j] = sway * t


