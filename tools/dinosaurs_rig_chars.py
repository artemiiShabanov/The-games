def paint_caveman():
    """Атлас пещерного человека: шкура через левое плечо с меховой кромкой, ожерелье из клыков,
    копна волос с чёлкой, голые руки и ноги с меховыми обмотками, рваный подол, копьё."""
    p = rm.Paint(211)
    # Торс: середина куска это грудь, левый бок героя справа. Шкура закрывает всё, кроме клина
    # вокруг правого плеча: спереди и сзади её край идёт наискось от правого бока к левому плечу.
    _hide(p, 0, 0, 32, 22, 26)
    for pts in ([(0, 0), (20.6, 0), (8, 13.4), (0, 5.2)], [(27.4, 0), (32, 0), (32, 5.2)]):
        p.poly(pts, SKIN, 124)
    p.grain(0, 0, 21, 13, 0.02, 1.0, 3.0)
    # Грудь и живот в вырезе: ключицы, грудные мышцы, рёбра, лопатка сзади.
    p.fold([(9.6, 2.6), (12.6, 3.3), (15.6, 2.7)], 0.3, 0.84, 22)
    p.fold([(9.0, 6.4), (11.6, 7.4), (14.4, 6.9)], 0.5, 0.82, 26)
    p.fold([(15.9, 3.2), (15.8, 7.2)], 0.3, 0.86, 20)
    p.ellipse(12.0, 5.2, 1.6, 0.9, SKIN_L)
    p.ellipse(11.6, 6.0, 0.28, 0.24, SKIN_D)
    for i in range(3):
        p.fold([(6.6 + i * 0.5, 8.0 + i * 1.4), (8.4 + i * 0.4, 8.5 + i * 1.4)], 0.24, 0.88, 14)
    p.fold([(2.0, 3.0), (3.4, 5.6), (2.6, 8.0)], 0.4, 0.86, 18)
    # Меховая кромка по косому краю шкуры, спереди и сзади.
    for edge in ([(20.6, 0.2), (8, 13.4)], [(8, 13.4), (0, 5.2)], [(32, 5.2), (27.4, 0.2)]):
        p.line(edge, FUR, 1.0, 168)
        (ax, ay), (bx, by) = edge
        for i in range(22):
            t = (i + p.rng.uniform(0.0, 1.0)) / 22.0
            cx, cy = ax + (bx - ax) * t, ay + (by - ay) * t
            p.line([(cx - 0.4, cy - 0.3), (cx + p.rng.uniform(0.2, 0.6), cy + p.rng.uniform(0.2, 0.5))], FUR_D if i % 3 else rgb("FFFFFF"), 0.11)
    # Шея и ворот: кожа кольцом, шнур ожерелья, клыки на груди.
    p.rect(0, 0, 32, 1.3, SKIN, 126)
    p.fold([(0, 1.35), (32, 1.35)], 0.3, 0.76, 30)
    p.line([(0, 1.9), (9, 2.2), (16, 3.0), (23, 2.2), (32, 1.9)], HAIR_D, 0.3, 170)
    for i, fx in enumerate((10.8, 12.9, 15.0, 17.0, 19.1, 21.2)):
        fy = 2.35 + 0.65 * (1.0 - abs(fx - 16.0) / 5.4)
        ln = 1.9 if i in (2, 3) else 1.4
        p.poly([(fx - 0.42, fy), (fx + 0.42, fy), (fx + 0.1, fy + ln)], BONE, 180)
        p.line([(fx - 0.2, fy + 0.1), (fx + 0.05, fy + ln * 0.85)], BONE_D, 0.1)
        p.ellipse(fx, fy, 0.3, 0.22, HAIR_D, 176)
    # Пояс-верёвка в два витка, костяная застёжка спереди.
    for by in (14.5, 15.5):
        p.band(0, by, 32, 0.8, FUR_D, 172, 0.06)
        for i in range(40):
            p.line([(i * 0.8, by + 0.75), (i * 0.8 + 0.5, by + 0.05)], HAIR, 0.1)
    p.fold([(0, 14.4), (32, 14.4)], 0.3, 0.66, 40)
    p.fold([(0, 16.4), (32, 16.4)], 0.3, 0.66, 40)
    p.poly([(13.8, 14.8), (14.6, 14.2), (15.4, 14.9), (17.0, 15.3), (18.0, 14.9), (18.6, 15.6), (18.0, 16.6), (17.0, 16.0),
            (15.4, 15.9), (14.6, 16.6), (13.8, 16.0), (14.2, 15.4)], BONE, 186)
    p.line([(14.4, 15.5), (18.0, 15.6)], BONE_D, 0.14)
    p.shade_v(0, 16.4, 32, 5.6, 0.92, 0.78)
    p.shade_v(0, 1.4, 32, 13, 1.05, 0.94)
    p.shade_round(0, 0, 32, 22, 0.76)
    # Голова: копна сверху и вокруг, лицо в середине куска, макушка на высоте 1,83.
    _hair(p, 32, 0, 32, 20, 150)
    p.poly([(40.6, 8.0), (55.4, 8.0), (55.6, 13.6), (54.2, 16.6), (51.2, 18.4), (50.6, 20), (45.4, 20), (44.8, 18.4),
            (41.8, 16.6), (40.4, 13.6)], SKIN, 126)
