"""Модели на скелете «Динозавров» для «продвинутых» (#144, состав в `docs/specs/settings.md`):
пещерный человек (слот `hero`), вождь-шаман в черепе тираннозавра (`captain`), прямоходящий
раптор (`enemy`). Те же три персонажа, что в `dinosaurs_mesh_chars.py`, плотнее и подробнее;
цвета из основы 16/32 (`dinosaurs16.PALETTE`).

Тела строит тот же `rig_models.build_body`, что и у пиратов: скелет из 17 костей, рост, плечи и
кисть `hand_r` под оружие прежние, поэтому позы и крепления демок сходятся. Свои только
пропорции, головы, навесные детали и рисунок атласа. Раскладка атласа пиратская
(`rig_models.regions`), в свободных углах лежат свои куски (подол, зубы, древко); голова из
`build_body` прячется внутри своей (копна волос, череп тираннозавра, череп раптора) и берёт
цвет из запасного куска. У раптора спрятанная голова ещё и сжата, чтобы узкий череп её закрыл.

Пружинные кости: у пещерного человека `tail` это копьё за спиной (качается наконечник с
перьями), у вождя `skirt` это накидка из шкуры, у раптора `sash` это хвост. Челюсть на кости у
раптора жёсткая, в правой кисти, вперёд, как жезл и сабля в зеркалах.

    python3 tools/dinosaurs_rig_chars.py --preview out.png
"""
