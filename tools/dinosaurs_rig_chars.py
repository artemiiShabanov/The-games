def dinosaurs_raptor():
    """Прямоходящий раптор: зелёная чешуя, жёлтое брюхо, длинная морда вперёд, гребень красных
    перьев, серпы когтей на ступнях, хвост на пружинной кости, в правой лапе челюсть на кости."""
    p = paint_raptor()
    reg = regions(p)
    r, _ = rm.build_body("enemy", reg, bulk=0.94, limb=0.86, leg="straight")
    # Спрятанная голова из `build_body` сжимается к оси шеи: узкий череп раптора её закрывает.
    for j, (x, y, z) in enumerate(r.verts):
        if y > 1.4705:
            r.verts[j] = (x * 0.5, 1.5 + (y - 1.5) * 0.62, z * 0.55 - 0.01)
    hw = lambda t, pos=None: [("head", 1.0)]
    # Шея: столбик от плеч к черепу, чуть вперёд.
    r.tube([(1.44, 0.082, 0.086, 0, 0.0), (1.5, 0.07, 0.076, 0, -0.004), (1.58, 0.064, 0.072, 0, -0.012), (1.67, 0.06, 0.07, 0, -0.02)],
           12, reg["strip"], lambda y: rm.blend(y, [("chest", 0.0, 1.44), ("neck", 1.47, 1.5), ("head", 1.56, 9.0)]))
    # Череп: лежит горизонтально, затылок позади шеи, длинная узкая морда вперёд и чуть вниз.
    skull = [((0.0, 1.71, 0.135), 0.03, 0.03), ((0.0, 1.714, 0.1), 0.082, 0.084), ((0.0, 1.716, 0.03), 0.104, 0.11),
             ((0.0, 1.71, -0.06), 0.107, 0.112), ((0.0, 1.696, -0.14), 0.094, 0.094), ((0.0, 1.678, -0.23), 0.07, 0.07),
             ((0.0, 1.66, -0.33), 0.052, 0.052), ((0.0, 1.648, -0.42), 0.044, 0.04), ((0.0, 1.642, -0.465), 0.026, 0.022)]
    crown = p.region(47, 0.6, 2, 1.2)
    path_tube(r, skull, 16, reg["own_head"], hw, cap_start=p.region(47, 18.4, 2, 1.2), cap_end=crown)
    # Гребень перьев: от темени к загривку, корни утоплены в череп.
    r.strip([(0.0, 1.828, -0.11), (0.0, 1.846, -0.03), (0.0, 1.838, 0.05), (0.0, 1.803, 0.11), (0.0, 1.753, 0.14)],
            (0.0, 0.92, 0.38), 0.085, reg["hat"], hw, 0.0, 0.0, 0.2)
    # Хвост на пружинной кости: от крестца назад и вниз, кончик приподнят.
    r.bone("sash", "hips", (-0.1, 0.98, 0.07))
    r.spring("sash", 50.0, 6.0, 0.3, (0.0, -0.3, 1.0))
    tail = [((0.0, 0.97, 0.03), 0.118, 0.11), ((0.0, 0.95, 0.17), 0.096, 0.094), ((0.0, 0.9, 0.34), 0.07, 0.068),
            ((0.0, 0.84, 0.52), 0.048, 0.046), ((0.0, 0.795, 0.69), 0.03, 0.029), ((0.0, 0.78, 0.83), 0.016, 0.015),
            ((0.0, 0.79, 0.93), 0.004, 0.004)]

    def tw(t, pos):
        k = max(0.0, min(1.0, (t - 0.04) / 0.3))
        return [("hips", 1.0 - k), ("sash", k)] if k < 1.0 else [("sash", 1.0)]

    path_tube(r, tail, 12, reg["tail"], tw)
    # Серпы когтей: на внутреннем пальце каждой ступни, подняты над землёй.
    for sx in (-1.0, 1.0):
        x = sx * (0.095 * 0.94 - 0.028)
        fw = lambda t, pos, s=("l" if sx < 0 else "r"): [("foot_" + s, 1.0)]
        path_tube(r, [((x, 0.075, -0.095), 0.02, 0.022), ((x, 0.125, -0.13), 0.017, 0.02), ((x, 0.15, -0.175), 0.012, 0.014),
                      ((x, 0.135, -0.215), 0.006, 0.007), ((x, 0.1, -0.232), 0.001, 0.001)], 6, reg["teeth"], fw, hint=(1.0, 0.0, 0.0))
    # Челюсть на кости в правой руке: жёсткая, вперёд, зубами вниз; вторая лента даёт толщину.
    hand_x = 0.228 * 0.94 * 1.058
    pts = [(hand_x, 0.8 + 0.01 * i, 0.06 - 0.105 * i) for i in range(7)]
    r.strip(pts, (0.0, 1.0, 0.0), 0.085, reg["club"], lambda t: [("hand_r", 1.0)], 0.0, 0.0, 0.0)
    core = p.region(41.1, 44, 1.3, 20)
    r.strip(pts, (1.0, 0.0, 0.0), 0.013, core, lambda t: [("hand_r", 1.0)], 0.0, 0.0, 0.0)
    return r, p


