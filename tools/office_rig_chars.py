def _cut_poly(p, points):
    """Прозрачный многоугольник: кончик галстука, лента пропуска."""
    rm.ImageDraw.Draw(p.a).polygon([(x * p.k, y * p.k) for x, y in points], fill=0)


def _tie_stripes(p, step, dark, light):
    """Косые полоски галстука в куске ленты: каждая обрезана по куску, соседей не задевает."""
    for i in range(-3, 8):
        for off, color, width, height in ((0.0, dark, 0.34, 140), (0.42, light, 0.09, None)):
            y0 = 34.5 + i * step + off
            xa, xb = max(40.0, 40.0 + (34.2 - y0) * 4.0), min(52.0, 40.0 + (41.9 - y0) * 4.0)
            if xb - xa > 0.3:
                p.line([(xa, y0 + (xa - 40.0) * 0.25), (xb, y0 + (xb - 40.0) * 0.25)], color, width, height)


def _tint(p, cx, cy, rx, ry, color, amount):
    """Мягкое пятно цвета: румянец, блик лысины, тень под челюстью."""
    x, y = max(cx - rx * 2.2, 0.0), max(cy - ry * 2.2, 0.0)
    w, h = min(cx + rx * 2.2, 64.0) - x, min(cy + ry * 2.2, 64.0) - y
    gx, gy = p._grid(x, y, w, h)
    t = (np.exp(-(((gx - cx) / rx) ** 2 + ((gy - cy) / ry) ** 2)) * amount)[..., None]
    ys, xs = p._slice(x, y, w, h)
    a = np.asarray(p.im, dtype=np.float32).copy()
    a[ys, xs] = a[ys, xs] * (1.0 - t) + np.array(color, dtype=np.float32) * t
    p.im = rm.Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
    p.d = rm.ImageDraw.Draw(p.im)


def _skin(p, x, y, w, h, base=SKIN):
    p.rect(x, y, w, h, base, 128)
    p.grain(x, y, w, h, 0.035, 1.0, 5.0)
    p.uneven(x, y, w, h, 0.04, 2.6)


def _pinstripe(p, x, y, w, h, color=SEA, step=1.14, width=0.13):
    """Костюмная полоска: тонкие светлые нити сверху вниз."""
    n = int(w / step)
    for i in range(n + 1):
        sx = x + 0.4 + i * step
        if sx < x + w - 0.1:
            p.line([(sx, y), (sx, y + h)], color, width)


def _eye(p, ex, ey, rx, ry, look=0.0, iris=DARK_D):
    """Глаз: веко, белок, радужка с бликом, тень ресниц сверху."""
