def _box(r, lo, hi, faces, weights):
    """Жёсткая коробка от угла `lo` до угла `hi`: `faces` это куски атласа граней `x-`, `x+`,
    `y-`, `y+`, `z-`, `z+` (каких нет, те не строятся). На гранях `x` развёртка идёт вдоль Z,
    верх куска это верх коробки."""
    (x0, y0, z0), (x1, y1, z1) = lo, hi
    quads = {
        "x-": ([(x0, y1, z1), (x0, y1, z0), (x0, y0, z0), (x0, y0, z1)], (-1, 0, 0)),
        "x+": ([(x1, y1, z0), (x1, y1, z1), (x1, y0, z1), (x1, y0, z0)], (1, 0, 0)),
        "y+": ([(x0, y1, z1), (x1, y1, z1), (x1, y1, z0), (x0, y1, z0)], (0, 1, 0)),
        "y-": ([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)], (0, -1, 0)),
        "z-": ([(x1, y1, z0), (x0, y1, z0), (x0, y0, z0), (x1, y0, z0)], (0, 0, -1)),
        "z+": ([(x0, y1, z1), (x1, y1, z1), (x1, y0, z1), (x0, y0, z1)], (0, 0, 1)),
    }
    for key, region in faces.items():
        pts, out = quads[key]
        u0, v0, u1, v1 = region
        ids = [r.vert(pos, uv, weights) for pos, uv in zip(pts, ((u0, v0), (u1, v0), (u1, v1), (u0, v1)))]
        r.tri(ids[0], ids[1], ids[2], out)
        r.tri(ids[0], ids[2], ids[3], out)


