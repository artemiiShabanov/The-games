def head_tube(r, reg, rings, top):
    """Своя голова поверх спрятанной: кольца `(y, rx, rz[, cz])` снизу вверх, перёд по центру куска
    головы, макушка на высоте `top`."""
    full = [(q[0], q[1], q[2], 0.0, q[3] if len(q) > 3 else -0.005) for q in rings]
    r.tube(full, 16, reg["own_head"], lambda y: [("head", 1.0)], cap_top=reg["crown"], v_range=(1.47, top))


def flip(region):
    """Тот же кусок вверх ногами: начало пути ляжет на низ куска."""
    u0, v0, u1, v1 = region
    return (u0, v1, u1, v0)


def sweep(r, pts, radii, n, region, weight, ref=(0.0, 0.0, 1.0), phase=0.0, cap_start=None, cap_end=None, cloth=0.0):
    """Труба вдоль ломаной в любую сторону (у `Rig.tube` кольца только горизонтальные): кольцо
    стоит поперёк пути, радиусы `(вдоль a, вдоль b)`, где `a` поперёк пути и `ref`. Развёртка: по
    кругу вдоль куска, по длине пути сверху вниз куска. `weight` это список весов или функция от
    середины кольца."""
    path = [np.array(q, dtype=float) for q in pts]
    along = [0.0]
    for a, b in zip(path, path[1:]):
        along.append(along[-1] + float(np.linalg.norm(b - a)))
    u0, v0, u1, v1 = region
    rows, tans = [], []
    for i, c in enumerate(path):
        t = path[min(i + 1, len(path) - 1)] - path[max(i - 1, 0)]
        t = t / np.linalg.norm(t)
        a = np.cross(t, np.array(ref, dtype=float))
        a = a / np.linalg.norm(a)
        b = np.cross(t, a)
        ra, rb = radii[i] if isinstance(radii[i], tuple) else (radii[i], radii[i])
        w = weight(c) if callable(weight) else weight
        v = v0 + (v1 - v0) * along[i] / along[-1]
        row = []
        for k in range(n + 1):
            phi = 2.0 * math.pi * k / n + phase
            pos = c + a * ra * math.cos(phi) + b * rb * math.sin(phi)
            row.append(r.vert(tuple(float(x) for x in pos), (u0 + (u1 - u0) * k / n, v), w, cloth))
        rows.append(row)
        tans.append(t)
    for i in range(len(rows) - 1):
        mid_axis = (path[i] + path[i + 1]) / 2.0
        for k in range(n):
            a, b, c, d = rows[i][k], rows[i][k + 1], rows[i + 1][k + 1], rows[i + 1][k]
            out = np.mean([r.verts[j] for j in (a, b, c, d)], axis=0) - mid_axis
            r.tri(a, b, c, out)
            r.tri(a, c, d, out)
    for cap, index, sign in ((cap_start, 0, -1.0), (cap_end, len(path) - 1, 1.0)):
        if cap is None:
            continue
        c0, d0, c1, d1 = cap
        w = weight(path[index]) if callable(weight) else weight
        hub = r.vert(tuple(float(x) for x in path[index]), ((c0 + c1) / 2.0, (d0 + d1) / 2.0), w, cloth)
        rim = [r.vert(r.verts[rows[index][k]], (c0 + (c1 - c0) * (0.5 + 0.45 * math.cos(2 * math.pi * k / n)),
                                                d0 + (d1 - d0) * (0.5 + 0.45 * math.sin(2 * math.pi * k / n))), w, cloth)
               for k in range(n)]
        for k in range(n):
            r.tri(hub, rim[k], rim[(k + 1) % n], tans[index] * sign)
    return rows


def two_sided(r, v_from, t_from):
    """Изнанка тонкой детали (корона, ворот, рваный подол): те же грани лицом внутрь на своих
    вершинах, чуть сдвинутых, чтобы гладкие нормали двух сторон не гасили друг друга."""
    remap = {}
    for i in range(v_from, len(r.verts)):
        x, y, z = r.verts[i]
        r.verts.append((x, y + 0.0003, z))
        r.uvs.append(r.uvs[i])
        r.weights.append(list(r.weights[i]))
        r.cloth.append(r.cloth[i])
        remap[i] = len(r.verts) - 1
    for a, b, c in list(r.tris[t_from:]):
        r.tris.append((remap[a], remap[c], remap[b]))


def follow_legs(r, v_from, top, bottom, share):
    """Подол идёт за ногами: от высоты `top` к `bottom` доля веса бёдер растёт до `share`, правая
    половина за правой ногой, левая за левой, середина поровну."""
    for i in range(v_from, len(r.verts)):
        x, y, _ = r.verts[i]
        t = max(0.0, min(1.0, (top - y) / (top - bottom)))
        a = share * t * t * (3.0 - 2.0 * t)
        if a <= 0.0:
            continue
        right = max(0.0, min(1.0, 0.5 + x / 0.14))
        acc = {}
        for bone, w in r.weights[i]:
            acc[bone] = acc.get(bone, 0.0) + w * (1.0 - a)
        acc["leg_r"] = acc.get("leg_r", 0.0) + a * right
        acc["leg_l"] = acc.get("leg_l", 0.0) + a * (1.0 - right)
        best = sorted(((b, w) for b, w in acc.items() if w > 0.001), key=lambda q: -q[1])[:4]
        total = sum(w for _, w in best)
        r.weights[i] = [(b, w / total) for b, w in best]


def add_cuffs(r, reg, k, t):
    """Раструбы рукавов у запястий: верх уходит внутрь рукава, низ закрыт тёмной крышкой."""
    for side, sx in (("l", -1.0), ("r", 1.0)):
        x = sx * 0.228 * k
        r.tube([(0.885, 0.07, 0.076, x * 1.05, 0.0), (0.93, 0.064, 0.069, x * 1.043, 0.0), (0.99, 0.051, 0.055, x * 1.034, 0.0),
                (1.05, 0.04 * t, 0.043 * t, x * 1.027, 0.0)], 12, reg["cuff"],
               lambda y, s=side: [("fore_" + s, 1.0)], cap_bottom=reg["head"])


def _cut_poly(p, points):
    """Прозрачный многоугольник: зубцы короны, рваный край."""
    rm.ImageDraw.Draw(p.a).polygon([(x * p.k, y * p.k) for x, y in points], fill=0)


def _star(p, x, y, size, color, core):
    """Вышитая звезда в четыре луча."""
    p.poly([(x, y - size), (x + size * 0.28, y - size * 0.28), (x + size, y), (x + size * 0.28, y + size * 0.28),
            (x, y + size), (x - size * 0.28, y + size * 0.28), (x - size, y), (x - size * 0.28, y - size * 0.28)], color, 150)
    p.ellipse(x, y, size * 0.26, size * 0.26, core)


def _rune(p, x, y, size, color):
    """Руна: стойка с двумя ветками."""
    p.line([(x, y - size), (x, y + size)], color, 0.16, 140)
    p.line([(x, y - size * 0.5), (x + size * 0.7, y - size)], color, 0.14, 140)
    p.line([(x, y + size * 0.1), (x + size * 0.7, y - size * 0.4)], color, 0.14, 140)


def _drape(p, x, y, w, h, count, dark=0.78, depth=44):
    """Складки тяжёлой ткани сверху вниз, чуть гуляют."""
    for i in range(count):
        fx = x + (i + 0.5) * w / count + p.rng.uniform(-0.3, 0.3)
        p.fold([(fx, y + 0.3), (fx + p.rng.uniform(-0.4, 0.4), y + h * 0.5), (fx + p.rng.uniform(-0.6, 0.6), y + h - 0.3)],
               p.rng.uniform(0.45, 0.85), dark, depth)


def _rivets(p, points, color, r=0.2):
    for x, y in points:
        p.ellipse(x, y, r, r, color, 168)
        p.ellipse(x - r * 0.3, y - r * 0.3, r * 0.4, r * 0.4, mul(color, 1.3))


def _fingers(p, color, y=45.4):
    for fx in (5.2, 7.0, 8.8, 10.6):
        p.line([(fx, y), (fx, 48)], color, 0.24, 104)


