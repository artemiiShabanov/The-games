def fantasy_goblin():
    """Гоблин: худой, большая голова с длинным носом и ушами шире плеч, бурая рубаха с рваным
    подолом, хвосты верёвочного пояса на пружине, в правой руке дубинка с костяными шипами."""
    p = paint_goblin()
    reg = regions(p)
    k, t = 0.94, 0.8
    r, _ = rm.build_body("enemy", reg, bulk=k, limb=t, leg="straight")
    head = [("head", 1.0)]
    # Голова широкая, с тяжёлой челюстью вперёд.
    head_tube(r, reg, [(1.47, 0.06, 0.064, -0.004), (1.5, 0.064, 0.068, -0.006), (1.522, 0.1, 0.098, -0.014),
                       (1.552, 0.136, 0.126, -0.022), (1.598, 0.158, 0.146, -0.022), (1.65, 0.161, 0.149, -0.016),
                       (1.7, 0.15, 0.141, -0.01), (1.745, 0.122, 0.119, -0.006), (1.778, 0.076, 0.079, -0.004),
                       (1.795, 0.03, 0.032, -0.004)], 1.8)
    # Нос крючком вперёд и вниз; начало спрятано в голове.
    sweep(r, [(0, 1.668, -0.12), (0, 1.652, -0.185), (0, 1.622, -0.24), (0, 1.585, -0.272), (0, 1.556, -0.278)],
          [(0.036, 0.034), (0.033, 0.031), (0.027, 0.026), (0.017, 0.017), (0.003, 0.003)], 8, reg["skin"], head,
          ref=(1.0, 0.0, 0.0))
    # Уши шире плеч: острые лопасти от висков в стороны, назад и вверх.
    for s in (-1.0, 1.0):
        pts = [(s * (0.125 + 0.08 * i), 1.655 + 0.036 * i, 0.0 + 0.018 * i) for i in range(5)]
        r.strip(pts, (0.0, 1.0, 0.0), 0.078, reg["pole"], lambda q: head, 0.0, 0.12, 0.94)
    # Рваный подол рубахи от ремня, изнанка видна в прорехах; идёт за ногами.
    vs, ts = len(r.verts), len(r.tris)
    r.tube([(0.7, 0.204, 0.176, 0, 0.0), (0.8, 0.188, 0.158, 0, 0.0), (0.9, 0.168, 0.134, 0, 0.0),
            (0.975, 0.15, 0.114, 0, 0.0), (1.012, 0.126, 0.09, 0, 0.0)], 16, reg["hat"], lambda y: [("hips", 1.0)],
           lambda y: max(0.0, min(1.0, (0.95 - y) / 0.25)) * 0.4)
    follow_legs(r, vs, 0.97, 0.7, 0.55)
    two_sided(r, vs, ts)
    # Хвосты верёвочного пояса: два конца на пружинной кости.
    r.bone("sash", "hips", (-0.1, 0.98, 0.07))
    r.spring("sash", 40.0, 5.0, 1.0)
    for dx, lean in ((-0.13, -0.03), (-0.07, 0.03)):
        pts = [(dx + lean * i, 0.99 - 0.06 * i, 0.105 + 0.016 * i) for i in range(6)]
        r.strip(pts, (1.0, 0.0, 0.0), 0.026, reg["strip"], lambda q: [("hips", 1.0 - q), ("sash", q)] if q < 1.0 else [("sash", 1.0)], 0.2)
    # Дубинка в правой руке вдоль −Z (на месте сабли скелета): рукоять проходит сквозь кисть,
    # толстый конец впереди, костяные шипы в два ряда.
    hand = [("hand_r", 1.0)]
    hand_x = 0.228 * k * 1.058
    rise = lambda z: 0.8 + (0.06 - z) * 0.095
    zs = [0.11, 0.085, 0.05, -0.14, -0.27, -0.38, -0.5, -0.585, -0.615]
    rad = [0.012, 0.026, 0.02, 0.024, 0.042, 0.068, 0.076, 0.062, 0.03]
    dark = p.region(36, 44, 28, 1.0)
    sweep(r, [(hand_x, rise(z), z) for z in zs], rad, 10, reg["skirt"], hand, ref=(0.0, 1.0, 0.0), cap_start=dark, cap_end=dark)
    for z, base, turn in ((-0.41, 0.07, 0.3), (-0.52, 0.074, 1.35)):
        for i in range(4):
            a = turn + i * math.pi / 2.0
            out = (math.cos(a), math.sin(a), 0.0)
            c = (hand_x, rise(z), z)
            pts = [tuple(c[j] + out[j] * d for j in range(3)) for d in (base - 0.02, base + 0.02, base + 0.075)]
            sweep(r, pts, [0.022, 0.016, 0.002], 5, flip(reg["gem"]), hand)
    return r, p


