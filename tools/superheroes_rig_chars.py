# Запасной кусок атласа под голову из `build_body`: она целиком внутри своей головы модели.
INNER = (60, 22, 4, 8)


def regions(p):
    reg = rm.regions(p)
    reg["own_head"] = reg["head"]
    reg["head"] = p.region(*INNER)
    return reg


def head_tube(r, reg, rings, top):
    """Своя голова поверх спрятанной: кольца `(y, rx, rz)` снизу вверх, перёд по центру куска
    головы, макушка на высоте `top`."""
    r.tube([(y, rx, rz, 0.0, -0.005) for y, rx, rz in rings], 16, reg["own_head"], lambda y: [("head", 1.0)],
           cap_top=reg["crown"], v_range=(1.47, top))


def _rivets(p, points, color, r=0.2):
    for x, y in points:
        p.ellipse(x, y, r, r, color, 168)
        p.ellipse(x - r * 0.3, y - r * 0.3, r * 0.4, r * 0.4, mul(color, 1.35))


def _cut_poly(p, points):
    """Прозрачный многоугольник (зубцы подола, просветы клешни)."""
    rm.ImageDraw.Draw(p.a).polygon([(x * p.k, y * p.k) for x, y in points], fill=0)


def _part(p, points, color, height=None):
    """Непрозрачная деталь поверх вырезанного куска."""
    p.poly(points, color, height)
    p.solid(points)


def _part_line(p, points, color, width, height=None):
    p.line(points, color, width, height)
    rm.ImageDraw.Draw(p.a).line([(x * p.k, y * p.k) for x, y in points], fill=255,
                                width=max(1, int(round(width * p.k))), joint="curve")


def _star(cx, cy, r, inner=0.42, turn=0.0):
    pts = []
    for i in range(10):
        a = math.pi * i / 5.0 - math.pi / 2.0 + turn
        k = r if i % 2 == 0 else r * inner
        pts.append((cx + math.cos(a) * k, cy + math.sin(a) * k))
    return pts


def _sheen(p, x, y, w, h, gain=0.16, at=0.34, width=0.1):
    """Блик гладкого материала (трико, резина, сталь): светлая полоса вдоль куска."""
    gx, gy = p._grid(x, y, w, h)
    t = np.exp(-((((gx - x) / w - at) / width) ** 2)) + 0.6 * np.exp(-((((gx - x) / w - (1.0 - at)) / (width * 0.7)) ** 2))
    p._apply(x, y, w, h, (1.0 + gain * t).astype(np.float32))


