"""Модели на скелете «Супергероев» для «продвинутых» (#137, состав в `docs/specs/settings.md`):
герой в синем трико с жёлтым плащом (слот `hero`), злодей-учёный (`captain`), робот-приспешник
(`enemy`). Зеркало `space_rig_chars.py`; те же три персонажа, что в `superheroes_mesh_chars.py`,
цвета оттуда же (палитра основы 16/32 `superheroes16.PALETTE`), рисунок плотнее и подробнее.

Тела строит тот же `rig_models.build_body`, что у пиратов и космоса, с теми же `bulk`: скелет из
17 костей, рост, плечи и кисть `hand_r` под оружие прежние, поэтому позы и крепления демок
сходятся. Свои только толщина рук и ног, головы, навесные детали и рисунок атласа. Раскладка
атласа пиратская (`rig_models.regions`); голова из `build_body` прячется внутри своей (волосы,
шлем, купол) и берёт цвет из запасного куска.

Пружинные кости (имена, родители и места как у космоса): у героя `tail` это плащ, у злодея
`skirt` это плащ, у робота `sash` это оборванные кабели у пояса. У плаща героя пружина мягче,
чем у антенны космонавта, и смотрит вниз: это ткань. У робота в правой кисти выдвижная клешня
на месте жезла пришельца: та же длина и направление вперёд.

    python3 tools/superheroes_rig_chars.py --preview out.png
"""
