#!/usr/bin/env python3
"""Модели на скелете «Космоса» для «продвинутых» (#136, состав в `docs/specs/settings.md`):
космонавт (слот `hero`), командир пришельцев (`captain`), пришелец-пехотинец (`enemy`).

Тела строит тот же `rig_models.build_body`, что и у пиратов: скелет из 17 костей, рост, плечи и
кисть `hand_r` под оружие прежние, поэтому позы и крепления демок сходятся. Свои только
пропорции, головы, навесные детали и рисунок атласа. Раскладка атласа пиратская
(`rig_models.regions`); голова из `build_body` прячется внутри своей (шлем, череп, купол) и
берёт цвет из запасного куска.

Пружинные кости: у космонавта `tail` это антенна ранца, у командира `skirt` это плащ, у
пехотинца `sash` это ленты пояса.

    python3 tools/space_rig_chars.py --preview out.png
"""
