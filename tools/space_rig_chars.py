def _alien_skin(p, x, y, w, h, base=ALIEN):
    """Кожа пришельца: фиолетовая, с пятнами и мелкой зернистостью."""
    p.rect(x, y, w, h, base, 128)
    p.grain(x, y, w, h, 0.06, 1.0, 8.0)
    p.uneven(x, y, w, h, 0.09, 2.6)
    p.stains(x, y, w, h, max(3, int(w * h / 60)), 1.1, 0.88)
    p.speckle(x, y, w, h, int(w * h / 5), mul(base, 0.8), 0.06)


def _alien_face(p, cx, eye_y, eye_rx, eye_ry, tilt, nose_y, mouth_y):
    """Лицо: миндалевидные чёрные глаза с бликом, две ноздри, рот щелью."""
    for sx in (-1.0, 1.0):
        ex = cx + sx * (eye_rx + 1.3)
        pts = []
        for i in range(20):
            a = 2 * math.pi * i / 20
            px, py = math.cos(a) * eye_rx, math.sin(a) * eye_ry * (1.0 - 0.35 * math.cos(a) * sx * -1.0)
            pts.append((ex + px, eye_y + py - px * tilt * sx))
        grown = [(ex + (qx - ex) * 1.14, eye_y + (qy - eye_y) * 1.2) for qx, qy in pts]
        p.poly(grown, mul(ALIEN_D, 0.8), 108)
        p.poly(pts, EYE, 150)
        p.ellipse(ex - sx * eye_rx * 0.3, eye_y - eye_ry * 0.45, eye_rx * 0.26, eye_ry * 0.22, rgb("D8E8FF"))
        p.ellipse(ex + sx * eye_rx * 0.35, eye_y + eye_ry * 0.3, eye_rx * 0.12, eye_ry * 0.12, rgb("6C7CA8"))
        p.ellipse(cx + sx * 0.5, nose_y, 0.22, 0.34, ALIEN_D, 104)
    p.line([(cx - 1.7, mouth_y), (cx, mouth_y + 0.25), (cx + 1.7, mouth_y)], mul(ALIEN_D, 0.7), 0.26, 104)
    p.line([(cx - 1.3, mouth_y + 0.7), (cx + 1.3, mouth_y + 0.7)], ALIEN_L, 0.14)


