#!/usr/bin/env python3
"""Модели на скелете «Сладостей» для «продвинутых» (#137, состав в `docs/specs/settings.md`):
пряничный человечек (слот `hero`), шоколадный король (`captain`), мармеладный мишка (`enemy`).
Те же три персонажа, что в `sweets_mesh_chars.py`, плотнее и подробнее; цвета из основы 16/32
(`sweets16.PALETTE`).

Тела строит тот же `rig_models.build_body`, что и у пиратов: скелет из 17 костей, рост, плечи и
кисть `hand_r` под оружие прежние, поэтому позы и крепления демок сходятся. Свои только
пропорции, головы, навесные детали и рисунок атласа. Раскладка атласа пиратская
(`rig_models.regions`), в свободных углах лежат свои куски (бант, ухо, зубец короны, морда,
бородка); голова из `build_body` прячется внутри своей (шар пряника, голова с короной, литая
голова мишки) и берёт цвет из запасного куска.

Пружинные кости: у пряника `tail` это концы красной ленты за шеей, у короля `skirt` это
мантия, у мишки `sash` это мармеладный хвостик. Вафельная трубочка мишки жёсткая, в правой
кисти, кремом вперёд, как жезл и сабля в зеркалах.

    python3 tools/sweets_rig_chars.py --preview out.png
"""
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rig_models as rm  # noqa: E402

rgb, mul, mix = rm.rgb, rm.mul, rm.mix

# Цвета те же, что в `sweets_mesh_chars.py` (палитра `sweets16.PALETTE` и светлые тона к ней);
# модуль мешей не импортируется, чтобы сборка моделей на скелете не тянула генератор low poly.
BREAD, BREAD_D, BREAD_L = rgb("C9803E"), rgb("945228"), rgb("E2A460")
ICING, ICING_D = rgb("FFF7EC"), rgb("D6BFCC")
MINT, MINT_D, MINT_L = rgb("86DBBE"), rgb("3FA99C"), rgb("D3F6E4")
PINK, PINK_D, PINK_L = rgb("FF8EB6"), rgb("B73A70"), rgb("FFC4DA")
JELLY, JELLY_D, JELLY_L = rgb("E63545"), rgb("A42244"), rgb("FF7482")
CARAMEL, CARAMEL_D, CARAMEL_L = rgb("F8CF6A"), rgb("D09038"), rgb("FFE9A8")
CHOCO, CHOCO_D, CHOCO_L = rgb("7C4838"), rgb("4A2826"), rgb("A86C50")
BLACK = rgb("2B161E")
WHITE = rgb("FFFFFF")

# Запасной кусок атласа под голову из `build_body`: она целиком внутри своей головы модели.
INNER = (60, 22, 4, 8)
# Свои куски в свободных углах пиратской раскладки.
SIDE = (52, 38, 12, 6)    # крыло банта, ухо мишки, зубец короны: обёрнут вокруг детали
WRAP = (16, 56, 20, 8)    # морда мишки, бородка короля: обёрнут вокруг детали
KNOT = (36, 22, 4, 8)     # узел банта; у мишки верх это торец морды с носом, низ торец трубочки
TOP = (60, 30, 4, 8)      # верх короны: малиновая подушка


def regions(p):
    reg = rm.regions(p)
    reg["own_head"] = reg["head"]
    reg["head"] = p.region(*INNER)
    reg["side"] = p.region(*SIDE)
    reg["wrap"] = p.region(*WRAP)
    reg["knot"] = p.region(*KNOT)
    reg["nose"] = p.region(36, 22, 4, 4)
    reg["hole"] = p.region(36, 26, 4, 4)
    reg["top"] = p.region(*TOP)
    return reg


def head_tube(r, reg, rings, top, cap=None):
    """Своя голова поверх спрятанной: кольца `(y, rx, rz)` снизу вверх, перёд по центру куска
    головы, макушка на высоте `top`."""
    r.tube([(y, rx, rz, 0.0, -0.005) for y, rx, rz in rings], 16, reg["own_head"], lambda y: [("head", 1.0)],
           cap_top=cap or reg["crown"], v_range=(1.47, top))


def body_weights(y):
    """Веса торса те же, что у трубы тела в `build_body`: накладка на торс гнётся вместе с ним."""
    return rm.blend(y, [("hips", 0.0, 0.97), ("spine", 1.07, 1.14), ("chest", 1.26, 1.435), ("neck", 1.475, 1.495),
                        ("head", 1.53, 9.0)])


def _turn(r, start, move, rx=0.0, rz=0.0):
    """Деталь, собранная стоя в нуле (вершины с номера `start`), повернуть вокруг X, затем вокруг
    Z (градусы) и перенести: трубы растут только вверх, а бант, морда и трубочка лежат."""
    ca, sa = math.cos(math.radians(rx)), math.sin(math.radians(rx))
    cb, sb = math.cos(math.radians(rz)), math.sin(math.radians(rz))
    for i in range(start, len(r.verts)):
        x, y, z = r.verts[i]
        y, z = y * ca - z * sa, y * sa + z * ca
        x, y = x * cb - y * sb, x * sb + y * cb
        r.verts[i] = (x + move[0], y + move[1], z + move[2])


