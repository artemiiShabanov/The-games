def _bread(p, x, y, w, h, base=BREAD):
    """Пряник: румяная корка с неровным загаром, тёмными порами и светлыми крошками."""
    p.rect(x, y, w, h, base, 128)
    p.grain(x, y, w, h, 0.07, 1.0, 9.0)
    p.uneven(x, y, w, h, 0.08, 2.6)
    p.stains(x, y, w, h, max(2, int(w * h / 80)), 1.0, 0.9)
    for _ in range(int(w * h / 4)):
        r = p.rng.uniform(0.05, 0.13)
        p.ellipse(x + p.rng.uniform(0.2, w - 0.2), y + p.rng.uniform(0.2, h - 0.2), r, r * 0.8, mul(base, 0.72), 104)
    p.speckle(x + 0.2, y + 0.2, w - 0.4, h - 0.4, int(w * h / 6), BREAD_L, 0.08)


def _icing_wave(p, x, y, w, n, thick=0.9, drop=0.8, shadow=BREAD_D):
    """Кайма глазури: выпуклая полоса с фестонами вниз, под ней тень, сверху блик."""
    step = w / n
    for dy, color, height in ((0.3, shadow, 116), (0.0, ICING, 178)):
        p.rect(x, y + dy, w, thick, color, height)
        for i in range(n):
            p.ellipse(x + (i + 0.5) * step, y + dy + thick, step * 0.37, drop, color, height)
    p.line([(x, y + thick + 0.05), (x + w, y + thick + 0.05)], ICING_D, 0.1)
    p.line([(x, y + 0.24), (x + w, y + 0.24)], WHITE, 0.14)
    for i in range(n):
        p.ellipse(x + (i + 0.38) * step, y + thick + drop * 0.3, step * 0.09, drop * 0.22, WHITE)


def _dragee(p, cx, cy, r, c, c_l, c_d, shadow=BREAD_D):
    """Драже: глянцевый шарик с бликом и тенью под ним."""
    p.ellipse(cx + r * 0.16, cy + r * 0.3, r * 1.08, r * 1.08, shadow, 112)
    p.ellipse(cx, cy, r, r, c_d, 176)
    p.ellipse(cx - r * 0.08, cy - r * 0.12, r * 0.84, r * 0.84, c, 190)
    p.ellipse(cx - r * 0.34, cy - r * 0.4, r * 0.32, r * 0.22, c_l, 196)
    p.ellipse(cx - r * 0.4, cy - r * 0.46, r * 0.13, r * 0.1, WHITE)


def _jelly(p, x, y, w, h, base=JELLY):
    """Мармелад: гладкая литая масса с глубиной цвета и редкими пузырьками."""
    p.rect(x, y, w, h, base, 128)
    p.uneven(x, y, w, h, 0.06, 3.0)
    p.grain(x, y, w, h, 0.02, 1.6, 3.0)
    for _ in range(max(2, int(w * h / 40))):
        r = p.rng.uniform(0.08, 0.16)
        bx, by = x + p.rng.uniform(0.4, w - 0.4), y + p.rng.uniform(0.4, h - 0.4)
        p.ellipse(bx, by, r, r, mul(base, 0.84))
        p.ellipse(bx - r * 0.3, by - r * 0.3, r * 0.4, r * 0.4, JELLY_L)


def _gloss(p, x0, y0, x1, y1, width=0.5):
    """Блик литья: белая полоска с мягким розовым ореолом и точкой рядом."""
    p.line([(x0, y0), (x1, y1)], JELLY_L, width * 1.9)
    p.line([(x0, y0), (x1, y1)], ICING, width, 150)
    p.ellipse(x1 + (x1 - x0) * 0.45, y1 + (y1 - y0) * 0.45, width * 0.5, width * 0.5, ICING, 150)


def _glow_band(p, x, y, w, h, rim=PINK):
    """Просвет желе у края: полоса светлеет книзу, по самому краю розовая кромка."""
    gx, gy = p._grid(x, y, w, h)
    p._apply(x, y, w, h, (1.0 + 0.3 * np.clip((gy - y) / h, 0.0, 1.0) ** 1.4).astype(np.float32))
    p.rect(x, y + h - 0.5, w, 0.5, rim, 132)


def _choco_tiles(p, x, y, w, h, cols, rows, base=CHOCO):
    """Плитка шоколада: дольки с фаской (свет сверху и слева, тень снизу и справа), бороздки."""
    p.rect(x, y, w, h, mul(base, 0.7), 92)
    tw, th = w / cols, h / rows
    for j in range(rows):
        for i in range(cols):
            tx, ty = x + i * tw, y + j * th
            p.rect(tx + 0.22, ty + 0.22, tw - 0.44, th - 0.44, mul(base, 0.86), 132)
            p.rect(tx + 0.75, ty + 0.75, tw - 1.5, th - 1.5, base, 158)
            p.line([(tx + 0.3, ty + th - 0.5), (tx + 0.3, ty + 0.3), (tx + tw - 0.5, ty + 0.3)], CHOCO_L, 0.2)
            p.line([(tx + 0.5, ty + th - 0.3), (tx + tw - 0.3, ty + th - 0.3), (tx + tw - 0.3, ty + 0.5)], CHOCO_D, 0.2)
            p.line([(tx + 1.2, ty + 1.25), (tx + tw * 0.55, ty + 1.25)], CHOCO_L, 0.12)
    p.grain(x, y, w, h, 0.05, 1.2, 6.0)


def _drips(p, x, y, w, band, lengths, shadow=CHOCO_D):
    """Потёки глазури: полоса и капли разной длины под ней, у каждой тень и блик."""
    step = w / len(lengths)
    for dx, dy, color, height in ((0.18, 0.26, shadow, 110), (0.0, 0.0, ICING, 178)):
        p.rect(x, y + dy, w, band, color, height)
        for i, length in enumerate(lengths):
            cx = x + (i + 0.5) * step + dx
            p.rect(cx - step * 0.36, y + dy + band - 0.1, step * 0.72, length + 0.1, color, height)
            p.ellipse(cx, y + dy + band + length, step * 0.36, step * 0.4, color, height)
    p.line([(x, y + 0.26), (x + w, y + 0.26)], WHITE, 0.14)
    for i, length in enumerate(lengths):
        p.ellipse(x + (i + 0.36) * step, y + band + length * 0.7, step * 0.08, max(0.12, length * 0.22), WHITE)


