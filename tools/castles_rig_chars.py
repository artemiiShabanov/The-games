def regions(p):
    reg = rm.regions(p)
    reg["own_head"] = reg["head"]
    reg["head"] = p.region(*INNER)
    reg["pauldron"] = p.region(*PAULDRON)
    reg["hem"] = p.region(*HEM)
    reg["shaft"] = p.region(*SHAFT)
    return reg


def head_tube(r, reg, rings, top):
    """Своя голова поверх спрятанной: кольца `(y, rx, rz)` снизу вверх, перёд по центру куска
    головы, макушка на высоте `top`."""
    r.tube([(y, rx, rz, 0.0, -0.005) for y, rx, rz in rings], 16, reg["own_head"], lambda y: [("head", 1.0)],
           cap_top=reg["crown"], v_range=(1.47, top))


# --- Общие приёмы рисунка -----------------------------------------------------------------------

def _rivets(p, points, color, r=0.2):
    for x, y in points:
        p.ellipse(x, y, r, r, color, 172)
        p.ellipse(x - r * 0.3, y - r * 0.3, r * 0.4, r * 0.4, mul(color, 1.35))


def _mail(p, x, y, w, h, base=IRON, period=0.72):
    """Кольчуга: ряды колец, каждый второй ряд сдвинут на полкольца; кольца выпуклые."""
    p.rect(x, y, w, h, base, 128)
    gx, gy = p._grid(x, y, w, h)
    row_h = period * 0.78
    row = np.floor(gy / row_h)
    fx = gx / period + 0.5 * (row % 2)
    cx, cy = fx - np.floor(fx) - 0.5, gy / row_h - row - 0.5
    ring = np.exp(-(((np.sqrt(cx * cx + cy * cy) - 0.33) / 0.12) ** 2))
    p._apply(x, y, w, h, (0.66 + 0.95 * ring).astype(np.float32), (ring * 34.0 - 12.0).astype(np.float32))
    p.uneven(x, y, w, h, 0.07, 2.4)


def _steel(p, x, y, w, h, color, scratches=6, height=150):
    """Пластина: ровный металл с разводами полировки и царапинами."""
    p.rect(x, y, w, h, color, height)
    p.grain(x, y, w, h, 0.05, 1.2, 6.0)
    p.uneven(x, y, w, h, 0.07, 2.6)
    for _ in range(scratches):
        sx, sy = x + p.rng.uniform(0.1, 0.9) * w, y + p.rng.uniform(0.1, 0.9) * h
        ln = p.rng.uniform(0.5, 1.6)
        p.line([(sx, sy), (min(sx + ln, x + w), min(max(sy + p.rng.uniform(-0.5, 0.5), y), y + h))], mul(color, 1.22), 0.08, height + 6)


def _lame(p, x, y, w, color, dark=0.62):
    """Край пластины внахлёст: светлая кромка и тень под ней."""
    p.rect(x, y - 0.32, w, 0.32, mul(color, 1.2), 172)
    p.fold([(x, y + 0.16), (x + w, y + 0.16)], 0.3, dark, 56)


def _cloth(p, x, y, w, h, color, folds=()):
    """Сукно: переплетение, выгоревшие места, складки сверху вниз по `folds` (доли ширины)."""
    p.rect(x, y, w, h, color, 128)
    p.weave(x, y, w, h, 0.4, 0.05)
    p.uneven(x, y, w, h, 0.08, 3.0)
    for f in folds:
        fx = x + w * f
        p.fold([(fx, y + 0.3), (fx + p.rng.uniform(-0.3, 0.3), y + h * 0.5), (fx + p.rng.uniform(-0.4, 0.4), y + h - 0.3)],
               p.rng.uniform(0.45, 0.8), 0.78, 40)


def _finger_lines(p, y0, color, xs=(5.2, 7.0, 8.8, 10.6)):
    for fx in xs:
        p.line([(fx, y0), (fx, 48)], color, 0.24, 104)


def _sabaton(p, color, dark):
    """Латный башмак 12×6: три пластины внахлёст, носок в середине куска, подошва по низу."""
    _steel(p, 40, 24, 12, 6, color, 3)
    for y in (25.4, 26.7, 27.9):
        _lame(p, 40, y, 12, color)
    p.fold([(46, 24.2), (46, 28.6)], 0.22, 0.8, 24)
    p.rect(40, 28.8, 12, 1.2, dark, 150)
    p.shade_round(40, 24, 12, 6, 0.72)


# --- Общая геометрия ----------------------------------------------------------------------------

def _flip(r, start):
    """Развернуть грани, добавленные после `start` (низ полей шляпы смотрит вниз)."""
    r.tris[start:] = [(a, c, b) for a, b, c in r.tris[start:]]


def _hem(r, reg, rings, sway=0.45):
    """Подол вокруг бёдер: труба от пояса вниз. Низ ходит за ногами (правая половина за правой
    ногой, левая за левой, середина за обеими), поэтому шаг не протыкает ткань."""
    first = len(r.verts)
    r.tube(rings, 16, reg["hem"], lambda y: [("hips", 1.0)])
    top, bottom = rings[-1][0], rings[0][0]
    for j in range(first, len(r.verts)):
        x, y, _ = r.verts[j]
        t = max(0.0, min(1.0, (top - y) / (top - bottom)))
        if x > 0.04:
            legs = [("leg_r", 0.6 * t)]
        elif x < -0.04:
            legs = [("leg_l", 0.6 * t)]
        else:
            legs = [("leg_l", 0.3 * t), ("leg_r", 0.3 * t)]
        ws = [("hips", 1.0 - 0.6 * t)] + legs
        r.weights[j] = [(b, w) for b, w in sorted(ws, key=lambda item: -item[1]) if w > 0.0]
        r.cloth[j] = sway * t


def _pauldron(r, reg, side, sx, x, k=1.0):
    """Наплечник: купол над плечом, сидит на руке и поднимается вместе с ней; низ утоплен в
    рукав, внутренний край в грудь."""
    w = lambda y: [("arm_" + side, 0.78), ("chest", 0.22)]
    r.tube([(1.325, 0.08 * k, 0.09 * k, x, 0.0), (1.365, 0.094 * k, 0.102 * k, x, 0.0), (1.405, 0.096 * k, 0.103 * k, x - sx * 0.004, 0.0),
            (1.438, 0.08 * k, 0.088 * k, x - sx * 0.012, 0.0), (1.458, 0.05 * k, 0.056 * k, x - sx * 0.02, 0.0),
            (1.466, 0.006, 0.006, x - sx * 0.024, 0.0)], 12, reg["pauldron"], w)


# --- Рыцарь -------------------------------------------------------------------------------------

SHIELD_HW, SHIELD_TOP, SHIELD_TIP = 0.155, 1.4, 0.94


def _shield_half(y):
    """Полуширина щита на высоте `y`: прямые борта до середины, ниже сходится к острию."""
    if y >= 1.17:
        return SHIELD_HW
    t = (1.17 - y) / (1.17 - SHIELD_TIP)
    return max(0.003, SHIELD_HW * (1.0 - t ** 1.7))


def _shield_outline(x0, y0, w, h, inset=0.0):
    """Контур щита в единицах атласа: кусок `w`×`h`, отступ `inset` внутрь."""
    span = SHIELD_TOP - SHIELD_TIP
    left, right = [], []
    for i in range(25):
        y = SHIELD_TOP - span * i / 24.0
        half = _shield_half(y) / SHIELD_HW * (w / 2.0) - inset
        ty = y0 + h * i / 24.0
        ty = min(max(ty, y0 + inset), y0 + h - inset * 2.2)
        left.append((x0 + w / 2.0 - max(half, 0.0), ty))
        right.append((x0 + w / 2.0 + max(half, 0.0), ty))
    return left + right[::-1]


