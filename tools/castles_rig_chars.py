def _shield(r, reg_face, reg_rim):
    """Щит за спиной: выгнутая по спине пластина, лицо в +Z (назад). Борта уходят в спину,
    поэтому между щитом и латами нет щели. Держится за грудь целиком, жёсткий."""
    weights = [("chest", 1.0)]
    ys = [SHIELD_TOP, 1.34, 1.27, 1.17, 1.11, 1.05, 1.0, 0.965, SHIELD_TIP]
    cols = 6
    base = lambda y: float(np.interp(y, [0.94, 1.05, 1.17, 1.3, 1.4], [0.1, 0.098, 0.106, 0.112, 0.092]))
    u0, v0, u1, v1 = reg_face
    front, edges = [], []
    for y in ys:
        half = _shield_half(y)
        row, pair = [], []
        for c in range(cols + 1):
            x = -half + 2.0 * half * c / cols
            bow = (x / SHIELD_HW) ** 2
            z = base(y) + 0.04 + 0.024 * (1.0 - bow) - 0.03 * bow
            uv = (u0 + (u1 - u0) * (x + SHIELD_HW) / (2.0 * SHIELD_HW), v0 + (v1 - v0) * (SHIELD_TOP - y) / (SHIELD_TOP - SHIELD_TIP))
            row.append(r.vert((x, y, z), uv, weights))
        front.append(row)
        for s in (-1.0, 1.0):
            bow = (half / SHIELD_HW) ** 2
            pair.append(((s * half, y, base(y) + 0.04 - 0.03 * bow), (s * half, y, base(y) - 0.05 * bow - 0.012)))
        edges.append(pair)
    for i in range(len(ys) - 1):
        for c in range(cols):
            a, b, cc, d = front[i][c], front[i][c + 1], front[i + 1][c + 1], front[i + 1][c]
            r.tri(a, b, cc, (0.0, 0.0, 1.0))
            r.tri(a, cc, d, (0.0, 0.0, 1.0))
    # Торец: левый и правый борт от кромки лица к спине, сверху полка.
    r0, t0, r1, t1 = reg_rim
    for side, s in ((0, -1.0), (1, 1.0)):
        for i in range(len(ys) - 1):
            v_a, v_b = t0 + (t1 - t0) * i / (len(ys) - 1), t0 + (t1 - t0) * (i + 1) / (len(ys) - 1)
            a = r.vert(edges[i][side][0], (r0, v_a), weights)
            b = r.vert(edges[i][side][1], (r1, v_a), weights)
            c = r.vert(edges[i + 1][side][1], (r1, v_b), weights)
            d = r.vert(edges[i + 1][side][0], (r0, v_b), weights)
            out = (s, -0.4 if i > 2 else 0.0, 0.0)
            r.tri(a, b, c, out)
            r.tri(a, c, d, out)
    a = r.vert(edges[0][0][0], (r0, t0), weights)
    b = r.vert(edges[0][1][0], (r1, t0), weights)
    c = r.vert(edges[0][1][1], (r1, t0 + (t1 - t0) * 0.12), weights)
    d = r.vert(edges[0][0][1], (r0, t0 + (t1 - t0) * 0.12), weights)
    r.tri(a, b, c, (0.0, 1.0, 0.0))
    r.tri(a, c, d, (0.0, 1.0, 0.0))


