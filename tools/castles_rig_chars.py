def castles_guard():
    """Стражник: худощавый, шлем-котелок с широкими полями поверх кольчужного капюшона, туника
    с подолом, кинжал в ножнах на пружине, алебарда в правой руке остриём вперёд."""
    p = paint_guard()
    reg = regions(p)
    r, _ = rm.build_body("enemy", reg, bulk=0.94, limb=0.88, leg="straight")
    # Голова в кольчужном капюшоне: чуть шире спрятанной, шея закрыта.
    head_tube(r, reg, [(1.47, 0.07, 0.074), (1.5, 0.072, 0.077), (1.525, 0.084, 0.09), (1.555, 0.099, 0.107),
                       (1.59, 0.109, 0.12), (1.63, 0.114, 0.125), (1.67, 0.114, 0.124), (1.705, 0.106, 0.116),
                       (1.735, 0.086, 0.096), (1.76, 0.05, 0.057)], 1.765)
    hw = lambda y: [("head", 1.0)]
    hat = reg["hat"]
    u0, v0, u1, v1 = hat
    span = v1 - v0
    dome = (u0, v0, u1, v0 + span * 0.66)
    brim = (u0, v0 + span * 0.74, u1, v0 + span * 0.92)
    edge = (u0, v0 + span * 0.95, u1, v1)
    # Шлем-котелок: низкий купол, широкие поля с наклоном вниз, кромка; низ полей смотрит вниз.
    r.tube([(1.698, 0.122, 0.132, 0, -0.005), (1.74, 0.117, 0.127, 0, -0.005), (1.78, 0.098, 0.107, 0, -0.005),
            (1.805, 0.066, 0.072, 0, -0.005), (1.817, 0.022, 0.024, 0, -0.005)], 16, dome, hw, cap_top=reg["sole"])
    r.tube([(1.664, 0.208, 0.218, 0, -0.005), (1.682, 0.165, 0.175, 0, -0.005), (1.7, 0.12, 0.13, 0, -0.005)], 16, brim, hw)
    r.tube([(1.652, 0.208, 0.218, 0, -0.005), (1.664, 0.208, 0.218, 0, -0.005)], 16, edge, hw)
    start = len(r.tris)
    r.tube([(1.652, 0.208, 0.218, 0, -0.005), (1.684, 0.108, 0.118, 0, -0.005)], 16, edge, hw)
    _flip(r, start)
    # Подол туники из-под ремня до середины бедра.
    hem = [(0.7, 0.2, 0.155, 0, 0), (0.78, 0.197, 0.147, 0, 0), (0.86, 0.188, 0.134, 0, 0),
           (0.92, 0.176, 0.122, 0, 0), (0.962, 0.166, 0.113, 0, 0), (0.983, 0.14, 0.103, 0, 0)]
    _hem(r, reg, hem)
    # Кинжал в ножнах на левом бедре: висит на поясе вдоль подола, качается на пружинной кости.
    r.bone("sash", "hips", (-0.1, 0.98, 0.07))
    r.spring("sash", 40.0, 5.0, 1.0)
    pts = []
    for i in range(6):
        y = 1.0 - 0.062 * i
        flare = float(np.interp(y, [ring[0] for ring in hem], [ring[1] for ring in hem])) + 0.014
        pts.append((-max(0.148 + (1.0 - y) * 0.1, flare if y < 0.983 else 0.0), y, 0.02 + 0.012 * i))
    weight = lambda t: [("hips", 1.0 - t), ("sash", t)] if t < 1.0 else [("sash", 1.0)]
    r.strip(pts, (0.0, 0.0, 1.0), 0.034, reg["strip"], weight, 0.0, 0.0, 0.5)
    r.strip(pts, (1.0, 0.0, 0.0), 0.013, reg["strip"], weight, 0.0, 0.0, 0.5)
    # Алебарда в правой руке: жёсткая, древко через кисть, железо впереди. Широкая лента стоит
    # ребром (топор вверх, крюк вниз), тонкая лежит плашмя и даёт древку толщину.
    hand_x = 0.228 * 0.94 * 1.058
    pts = [(hand_x, 0.8 + 0.01 * i, 0.34 - 0.19 * i) for i in range(7)]
    r.strip(pts, (0.0, 1.0, 0.0), 0.2, reg["skirt"], lambda t: [("hand_r", 1.0)], 0.0, 0.0, 0.0)
    shaft = [(hand_x, 0.8 + 0.01 * i * 0.78, 0.34 - 0.19 * i * 0.78) for i in range(7)]
    r.strip(shaft, (1.0, 0.0, 0.0), 0.014, reg["shaft"], lambda t: [("hand_r", 1.0)], 0.0, 0.0, 0.0)
    return r, p


