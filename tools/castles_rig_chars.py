def _rivets(p, points, color, r=0.2):
    for x, y in points:
        p.ellipse(x, y, r, r, color, 168)
        p.ellipse(x - r * 0.3, y - r * 0.3, r * 0.4, r * 0.4, mul(color, 1.35))


def _steel(p, x, y, w, h, base, amount=0.05):
    """Полированный металл: зерно, разводы и редкие царапины."""
    p.rect(x, y, w, h, base, 128)
    p.grain(x, y, w, h, amount, 0.9, 8.0)
    p.uneven(x, y, w, h, 0.05, 3.0)
    for _ in range(max(2, int(w * h / 40))):
        sx, sy = x + p.rng.uniform(0.5, w - 0.5), y + p.rng.uniform(0.5, h - 0.5)
        p.line([(sx, sy), (sx + p.rng.uniform(-1.4, 1.4), sy + p.rng.uniform(-0.4, 0.4))], mul(base, 1.2), 0.07, 140)


def _sheen(p, x, y, w, h, cx, wid, gain):
    """Блик вертикальной полосой: выпуклая пластина ловит свет."""
    gx, gy = p._grid(x, y, w, h)
    p._apply(x, y, w, h, (1.0 + gain * np.exp(-(((gx - cx) / wid) ** 2))).astype(np.float32))


def _lames(p, x, y, w, h, n, base, edge, rim=None):
    """Наползающие пластины: полосы с градиентом, тёмный шов и светлая кромка под каждой."""
    step = h / n
    for i in range(n):
        y0 = y + i * step
        p.rect(x, y0, w, step, base, 134)
        p.shade_v(x, y0, w, step, 1.14, 0.76)
        p.fold([(x, y0 + step), (x + w, y0 + step)], 0.3, 0.58, 56)
        p.line([(x, y0 + 0.08), (x + w, y0 + 0.08)], edge, 0.12, 160)
    if rim is not None:
        p.rect(x, y + h - 0.5, w, 0.5, rim, 172)


def _mail(p, x, y, w, h, base, hi, pw=0.5, ph=0.36, ring=0.18):
    """Кольчуга: смещённые ряды колец, между ними тёмная щель, рельеф на каждом кольце."""
    p.rect(x, y, w, h, base, 128)
    gx, gy = p._grid(x, y, w, h)
    row = np.floor(gy / ph)
    off = (row % 2) * pw / 2.0
    fx = ((gx + off) % pw) - pw / 2.0
    fy = (gy % ph) - ph / 2.0
    d = np.sqrt(fx ** 2 + (fy * pw / ph) ** 2)
    t = np.exp(-(((d - ring) / 0.055) ** 2)).astype(np.float32)
    p._apply(x, y, w, h, 0.55 + 0.95 * t, (t - 0.35) * 22.0)
    ys, xs = p._slice(x, y, w, h)
    a = np.asarray(p.im, dtype=np.float32).copy()
    a[ys, xs] = a[ys, xs] + (np.array(hi, dtype=np.float32) - np.array(base, dtype=np.float32)) * (t[..., None] * 0.34)
    p.im = rm.Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
    p.d = rm.ImageDraw.Draw(p.im)
    p.uneven(x, y, w, h, 0.07, 2.6)


def _cloth(p, x, y, w, h, base, relief=12.0, weave=0.4, depth=0.05):
    p.rect(x, y, w, h, base, 128)
    p.weave(x, y, w, h, weave, depth, relief)
    p.uneven(x, y, w, h, 0.08, 3.0)


def _folds(p, x, y, w, h, count, dark=0.78, width=0.6):
    """Вертикальные складки ткани сверху вниз с лёгким уходом в сторону."""
    for i in range(count):
        fx = x + w * (i + 0.5) / count + p.rng.uniform(-0.3, 0.3)
        p.fold([(fx, y + 0.3), (fx + p.rng.uniform(-0.5, 0.5), y + h * 0.5), (fx + p.rng.uniform(-0.7, 0.7), y + h - 0.3)],
               p.rng.uniform(width * 0.7, width * 1.2), dark, 44)


def _shield(p, cx, y, w, h, field, charge, trim):
    """Геральдический щит на груди: рамка, поле и крест."""
    pts = lambda g: [(cx - w / 2 + g, y + g), (cx + w / 2 - g, y + g), (cx + w / 2 - g, y + h * 0.62),
                     (cx, y + h - g * 1.2), (cx - w / 2 + g, y + h * 0.62)]
    p.poly(pts(0.0), trim, 168)
    p.poly(pts(0.38), field, 150)
    p.rect(cx - 0.45, y + 0.9, 0.9, h * 0.78, charge, 160)
    p.rect(cx - w * 0.3, y + h * 0.28, w * 0.6, 0.9, charge, 160)


