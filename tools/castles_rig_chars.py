def _tabard_skirt(r, reg, k, rings, weights, region, open_sides=True):
    """Юбка табарда: два полотнища, спереди и сзади, бока открыты. Колышется у низа."""
    sides = {(i, kk) for i in range(len(rings) - 1) for kk in (3, 4, 11, 12)} if open_sides else set()
