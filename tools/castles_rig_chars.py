    r.tube([(1.7, 0.122, 0.132, 0, -0.005), (1.735, 0.13, 0.14, 0, -0.005), (1.775, 0.126, 0.136, 0, -0.005),
            (1.805, 0.1, 0.108, 0, -0.005), (1.822, 0.056, 0.06, 0, -0.005)], 16, reg["dome"], lambda y: [("head", 1.0)],
           cap_top=reg["dome"], v_range=(1.7, 1.826))
    r.tube([(1.665, 0.2, 0.21, 0, -0.005), (1.68, 0.185, 0.195, 0, -0.005), (1.704, 0.15, 0.16, 0, -0.005),
            (1.726, 0.128, 0.138, 0, -0.005)], 16, reg["brim"], lambda y: [("head", 1.0)], v_range=(1.665, 1.726))
    # Юбка туники: колокол до колена, ровный, вокруг всего пояса.
    _tabard_skirt(r, reg, k, [(0.68, 0.262, 0.248, 0, 0.0), (0.76, 0.236, 0.222, 0, 0.0), (0.84, 0.21, 0.19, 0, 0.0),
                              (0.93, 0.185, 0.155, 0, 0.0)],
                  lambda y: [("hips", 1.0)], reg["tunic"], open_sides=False)
    # Концы пояса: два хвоста багровой ткани на пружинной кости.
    r.bone("sash", "hips", (-0.1, 0.98, 0.07))
    r.spring("sash", 40.0, 5.0, 1.0)
    for dx, lean in ((-0.13, -0.03), (-0.07, 0.03)):
        pts = [(dx + lean * i, 0.99 - 0.06 * i, 0.15 + 0.024 * i) for i in range(6)]
        r.strip(pts, (1.0, 0.0, 0.0), 0.03, reg["strip"], lambda t: [("hips", 1.0 - t), ("sash", t)] if t < 1.0 else [("sash", 1.0)], 0.2)
    # Меч в правой руке: клинок вперёд, жёсткий, на том же месте, что сабля скелета у пиратов.
    hand_x = 0.228 * k * 1.058
    pts = [(hand_x, 0.8 + 0.012 * i, -0.02 - 0.115 * i) for i in range(7)]
    r.strip(pts, (0.0, 1.0, 0.0), 0.03, reg["blade"], lambda t: [("hand_r", 1.0)], 0.0, 0.0, 0.75)
    # Перекрестие: короткая поперечная планка у рукояти.
    gz = -0.02 - 0.115 * 1.5
    r.strip([(hand_x - 0.075, 0.8 + 0.012 * 1.5, gz), (hand_x + 0.075, 0.8 + 0.012 * 1.5, gz)], (0.0, 1.0, 0.0), 0.014,
            reg["guard"], lambda t: [("hand_r", 1.0)], 0.0, 0.0, 0.0)
    return r, p


