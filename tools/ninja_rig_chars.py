def _flip(r, start):
    """Развернуть грани, добавленные после `start` (изнанка накидки и назатыльника)."""
    r.tris[start:] = [(a, c, b) for a, b, c in r.tris[start:]]


def _rod(r, a, b, profile, n, region, weights, side=(1.0, 0.0, 0.0), cap_a=None, cap_b=None):
    """Стержень вдоль отрезка `a`..`b` с кольцами поперёк оси: `profile` это `(доля длины,
    полуширина вдоль side, полутолщина)`. Развёртка: низ куска у `a`, верх у `b`."""
    a, b = np.array(a, dtype=float), np.array(b, dtype=float)
    axis = (b - a) / np.linalg.norm(b - a)
    u = np.array(side, dtype=float)
    u = u - axis * float(np.dot(u, axis))
    u = u / np.linalg.norm(u)
    v = np.cross(axis, u)
    u0, v0, u1, v1 = region
    rows, mids = [], []
    for t, ru, rv in profile:
        c = a + (b - a) * t
        mids.append(c)
        row = []
        for k in range(n + 1):
            ang = 2.0 * math.pi * k / n
            pos = c + u * ru * math.sin(ang) + v * rv * math.cos(ang)
            row.append(r.vert(tuple(float(q) for q in pos), (u0 + (u1 - u0) * k / n, v1 - (v1 - v0) * t), list(weights)))
        rows.append(row)
    for i in range(len(rows) - 1):
        for k in range(n):
            q = (rows[i][k], rows[i][k + 1], rows[i + 1][k + 1], rows[i + 1][k])
            mid = np.mean([r.verts[j] for j in q], axis=0)
            out = mid - (mids[i] + mids[i + 1]) / 2.0
            r.tri(q[0], q[1], q[2], out)
            r.tri(q[0], q[2], q[3], out)
    for cap, row, c, out in ((cap_a, rows[0], mids[0], -axis), (cap_b, rows[-1], mids[-1], axis)):
        if cap is None:
            continue
        c0, d0, c1, d1 = cap
        hub = r.vert(tuple(float(q) for q in c), ((c0 + c1) / 2.0, (d0 + d1) / 2.0), list(weights))
        rim = [r.vert(r.verts[row[k]], ((c0 + c1) / 2.0 + (c1 - c0) * 0.45 * math.sin(2.0 * math.pi * k / n),
                                        (d0 + d1) / 2.0 + (d1 - d0) * 0.45 * math.cos(2.0 * math.pi * k / n)), list(weights))
               for k in range(n)]
        for k in range(n):
            r.tri(hub, rim[k], rim[(k + 1) % n], out)


def _hem(r, region, rings, sway=0.45):
    """Подол вокруг бёдер: труба от пояса вниз. Низ ходит за ногами (правая половина за правой
    ногой, левая за левой, середина за обеими), поэтому шаг не протыкает ткань."""
    first = len(r.verts)
    r.tube(rings, 16, region, lambda y: [("hips", 1.0)])
    top, bottom = rings[-1][0], rings[0][0]
    for j in range(first, len(r.verts)):
        x, y, _ = r.verts[j]
        t = max(0.0, min(1.0, (top - y) / (top - bottom)))
        if x > 0.04:
            legs = [("leg_r", 0.6 * t)]
        elif x < -0.04:
            legs = [("leg_l", 0.6 * t)]
        else:
            legs = [("leg_l", 0.3 * t), ("leg_r", 0.3 * t)]
        ws = [("hips", 1.0 - 0.6 * t)] + legs
        r.weights[j] = [(b, w) for b, w in sorted(ws, key=lambda item: -item[1]) if w > 0.0]
        r.cloth[j] = sway * t


def _pants(r, reg, k, t, puff=1.0):
    """Широкие штаны до колена поверх ноги: напуск над завязкой под коленом. Рисунок тот же кусок
    ноги на тех же высотах, верх и низ утоплены в ногу."""
    for side, sx in (("l", -1.0), ("r", 1.0)):
        x = sx * 0.095 * k
        lw = lambda y, s=side: rm.blend(y, [("foot_" + s, 0.0, 0.07), ("shin_" + s, 0.11, 0.43), ("leg_" + s, 0.55, 0.86),
                                            ("hips", 0.96, 9.0)])
        q = t * puff
        r.tube([(0.44, 0.063 * t, 0.069 * t, x, 0.0), (0.462, 0.083 * q, 0.089 * q, x, 0.0), (0.51, 0.095 * q, 0.101 * q, x, 0.0),
                (0.6, 0.1 * q, 0.106 * q, x, 0.0), (0.72, 0.104 * q, 0.11 * q, x, 0.0), (0.83, 0.105 * q, 0.111 * q, x, 0.0),
                (0.9, 0.1 * q, 0.106 * q, x * 0.98, 0.0), (0.95, 0.087 * t, 0.095 * t, x * 0.9, 0.0)], 12, reg["leg"], lw,
               lambda y: 0.22 if 0.46 < y < 0.86 else 0.0, v_range=(0.07, 0.95))


