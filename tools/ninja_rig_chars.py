def _cut_poly(p, points):
    """Прозрачный многоугольник."""
    rm.ImageDraw.Draw(p.a).polygon([(x * p.k, y * p.k) for x, y in points], fill=0)


def _spiral(p, x, y, w, h, pitch, color=None, width=0.22, dark=0.72):
    """Витки обмотки: косые линии с шагом `pitch`, на шве сходятся виток в виток. Без цвета это
    вдавленные складки, с цветом шнур поверх."""
    i = 0
    while y + i * pitch < y + h:
        y0 = y + i * pitch
        if color is None:
            p.fold([(x, y0), (x + w, y0 + pitch)], width, dark, 46)
        else:
            p.line([(x, y0), (x + w, y0 + pitch)], color, width, 160)
        i += 1


def _lames(p, x, y, w, h, rows, base, lace, step, edge=None, lace_w=0.3):
    """Пластины доспеха рядами: блик лака по верху, тень под рядом, стежки шнуровки через шаг."""
    rh = h / rows
    for i in range(rows):
        ry = y + i * rh
        p.rect(x, ry, w, rh, base, 150)
        p.rect(x, ry + rh * 0.06, w, rh * 0.16, mul(base, 1.7), 170)
        p.rect(x, ry + rh * 0.7, w, rh * 0.3, mul(base, 0.55), 112)
        j = 0
        while (j + 0.5 + 0.5 * (i % 2)) * step < w:
            p.rect(x + (j + 0.5 + 0.5 * (i % 2)) * step - lace_w / 2.0, ry + rh * 0.62, lace_w, rh * 0.38, lace, 162)
            j += 1
    if edge:
        p.rect(x, y + h - rh * 0.3, w, rh * 0.3, edge, 178)


