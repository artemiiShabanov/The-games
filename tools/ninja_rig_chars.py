    # Концы пояса: два хвоста от узла на левом бедре сзади, на пружинной кости.
    r.bone("sash", "hips", (-0.1, 0.98, 0.07))
    r.spring("sash", 40.0, 5.0, 1.0)
    for dx, lean, n in ((-0.118, -0.012, 6), (-0.072, 0.007, 5)):
        pts = [(dx + lean * i, 0.985 - 0.06 * i, 0.094 + 0.015 * i) for i in range(n)]
        r.strip(pts, (1.0, 0.0, 0.0), 0.03, reg["strip"], lambda t: [("hips", 1.0 - t), ("sash", t)] if t < 1.0 else [("sash", 1.0)], 0.2)
    # Серп кама в правой руке: жёсткий. Древко через кисть вперёд, пятка за кистью; лезвие
    # лентой ребром, клюв от конца древка вниз и к себе.
    hand_x = 0.228 * k * 1.058
    hand = [("hand_r", 1.0)]
    steel = p.region(60.2, 55.6, 3.0, 3.6)
    _rod(r, (hand_x, 0.795, 0.09), (hand_x, 0.855, -0.56), [(0.0, 0.015, 0.015), (0.03, 0.017, 0.017), (0.9, 0.014, 0.014), (1.0, 0.016, 0.016)],
         6, reg["shaft"], hand, cap_a=steel, cap_b=steel)
    r.strip([(hand_x, 0.735, -0.43), (hand_x, 0.735, -0.6)], (0.0, 1.0, 0.0), 0.14, reg["skirt"], lambda t: hand, 0.0, 0.0, 0.0)
    return r, p


