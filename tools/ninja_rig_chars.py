    _rod(r, at(0.714), at(1.0), [(0.0, 0.021, 0.015), (0.5, 0.019, 0.014), (0.94, 0.021, 0.015), (1.0, 0.023, 0.017)], 8,
         p.region(44, 44, 8, 12), back, cap_b=gold)
    _pants(r, reg, k, 0.98)
    _hem(r, reg["hem"], [(0.79, 0.218, 0.152, 0, 0), (0.85, 0.214, 0.148, 0, 0), (0.91, 0.202, 0.138, 0, 0),
                         (0.955, 0.186, 0.128, 0, 0), (0.975, 0.168, 0.12, 0, 0), (0.99, 0.148, 0.107, 0, 0)])
