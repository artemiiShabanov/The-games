  function pathFor(sprite) {
    let d = "";
    sprite.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") d += `M${x} ${y}h1v1h-1z`;
    });
    return d;
  }
  function put(svg, sprite, x, y, color) {
    const p = document.createElementNS("http://www.w3.org/2000/svg", "path");
    p.setAttribute("d", pathFor(sprite));
    p.setAttribute("fill", color || "#1E2A4A");
    p.setAttribute("transform", `translate(${x} ${y})`);
    svg.appendChild(p);
  }
